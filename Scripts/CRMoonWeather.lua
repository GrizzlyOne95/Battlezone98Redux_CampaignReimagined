local function Fx_Create(kind, template, x, y, z)
    if V.SystemCount >= V.MaxSystems then
        return nil
    end
    if (V.TemplateFailures[template] or 0) >= V.MaxFailuresPerTemplate then
        return nil
    end

    V.Serial = V.Serial + 1
    local name = "cr_mw_" .. kind .. "_" .. tostring(V.Serial)
    if Call("CreateParticleSystem", name, template, Vec(x, y, z)) ~= true then
        local failures = (V.TemplateFailures[template] or 0) + 1
        V.TemplateFailures[template] = failures
        if failures >= V.MaxFailuresPerTemplate then
            print("CRMoonWeather: " .. template .. " disabled after " .. tostring(failures) ..
                " failed particle creates (template unavailable)")
        end
        return nil
    end

    V.TemplateFailures[template] = 0
    V.Systems[name] = kind
    V.SystemCount = V.SystemCount + 1
    Call("SetParticleSystemKeepLocalSpace", name, false)
    Call("SetParticleSystemNonVisibleUpdateTimeout", name, 3.0)
    return name
end

local function Fx_Destroy(name)
    if name == nil or V.Systems[name] == nil then return end
    Call("DestroyParticleSystem", name)
    V.Systems[name] = nil
    V.SystemCount = V.SystemCount - 1
end

local function Fx_DestroyAll()
    local names = {}
    for name in pairs(V.Systems) do names[#names + 1] = name end
    for i = 1, #names do Fx_Destroy(names[i]) end
    V.SystemCount = 0
end

-- =============================================================================
-- Density, breath and the glow timeline
-- =============================================================================

local function BuildTimeline(seed)
    V.Seed = seed
    V.GlowRng = Map.NewRng(Map.DeriveSeed(seed, 31))
    V.BreathPhase = Map.NewRng(Map.DeriveSeed(seed, 32)).Next()
    V.GlowWindows = {}
    V.GlowCursor = 0.0
end

-- One window = five draws, always in the same order, so the list is a pure
-- function of the seed however it is extended.
local function ExtendGlowTimeline(upTo)
    local rng = V.GlowRng
    if rng == nil then return end
    while V.GlowCursor < upTo and #V.GlowWindows < 400 do
        local rise = rng.Range(V.GlowRise[1], V.GlowRise[2])
        local hold = rng.Range(V.GlowHold[1], V.GlowHold[2])
        local fall = rng.Range(V.GlowFall[1], V.GlowFall[2])
        local strength = rng.Range(V.GlowStrength[1], V.GlowStrength[2])
        local gap
        if #V.GlowWindows == 0 then
            gap = rng.Range(V.GlowFirst[1], V.GlowFirst[2])
        else
            gap = rng.Range(V.GlowGap[1], V.GlowGap[2])
        end
        local start = V.GlowCursor + gap
        V.GlowWindows[#V.GlowWindows + 1] = {
            start = start, rise = rise, hold = hold, fall = fall, strength = strength,
        }
        V.GlowCursor = start + rise + hold + fall
    end
end

local function Envelope(w, t)
    local age = t - w.start
    if age <= 0.0 then return 0.0 end
    if age < w.rise then return w.strength * SmoothStep(age / w.rise) end
    age = age - w.rise
    if age < w.hold then return w.strength end
    age = age - w.hold
    if age < w.fall then return w.strength * (1.0 - SmoothStep(age / w.fall)) end
    return 0.0
end

-- The seeded timeline's glow at an absolute time; a pure function of the seed.
function V.GlowAt(t)
    if V.GlowRng == nil or not V.AllowRandomGlow or not V.AllowGlow then return 0.0 end
    ExtendGlowTimeline(t + V.GlowLookahead)
    local best = 0.0
    for i = 1, #V.GlowWindows do
        local w = V.GlowWindows[i]
        if w.start > t then break end
        local e = Envelope(w, t)
        if e > best then best = e end
    end
    return best
end

local function ScriptedGlowAt(t)
    local best = 0.0
    for i = 1, #V.Scripted do
        local e = Envelope(V.Scripted[i], t)
        if e > best then best = e end
    end
    return best
end

local function UpdateGlow()
    local seeded = V.Synced and V.GlowAt(V.Clock) or 0.0
    local scripted = V.AllowGlow and ScriptedGlowAt(V.Clock) or 0.0
    V.GlowLevel = math.max(seeded, scripted)
    if V.GlowLevel > V.Stats.peakGlow then V.Stats.peakGlow = V.GlowLevel end

    -- Drop scripted glows that have finished.
    for i = #V.Scripted, 1, -1 do
        local w = V.Scripted[i]
        if V.Clock >= w.start + w.rise + w.hold + w.fall then table.remove(V.Scripted, i) end
    end
end

function V.GetGlow() return V.GlowLevel end
function V.IsGlowing() return V.GlowLevel > 0.02 end
function V.GetGlowWindows() return V.GlowWindows end

-- 1 +/- BreathDepth, slow. No random draws: a pure function of clock and seed.
function V.GetBreath()
    local turn = (V.Clock / V.BreathPeriod) + V.BreathPhase
    return 1.0 + (V.BreathDepth * math.sin(turn * 2.0 * math.pi))
end

function V.GetDensity() return V.Density end

-- Everything that scales how much mist is emitted: density x breath x glow.
function V.GetMistScale()
    return V.DensityValue * V.GetBreath() * (1.0 + (V.GlowRateBoost * V.GlowLevel)) * V.Quality
end

local function UpdateDensity(dt)
    local step = V.DensityRate * dt
    local delta = V.Density - V.DensityValue
    if delta > step then delta = step end
    if delta < -step then delta = -step end
    V.DensityValue = Clamp(V.DensityValue + delta, V.DensityLimit[1], V.DensityLimit[2])
end

-- =============================================================================
-- Mist colour (the glow)
-- =============================================================================

-- The templates' ColourInterpolator is affector 0; colour1 is the body of a
-- card's life and colour2 the late part. The glow brightens both and lifts alpha.
local function MistColours(glow)
    local mix = V.GlowColorMix * glow
    local r = Lerp(V.MistColor.r, V.GlowColor.r, mix)
    local g = Lerp(V.MistColor.g, V.GlowColor.g, mix)
    local b = Lerp(V.MistColor.b, V.GlowColor.b, mix)
    local lift = V.GlowAlphaLift * glow
    return
        string.format("%.3f %.3f %.3f %.3f", r, g, b, V.MistAlphaA + lift),
        string.format("%.3f %.3f %.3f %.3f", r * 0.94, g * 0.94, b * 0.96, V.MistAlphaB + (lift * 0.8))
end

local function ApplyMistColour(record, glow)
    if record.glow ~= nil and math.abs(glow - record.glow) < V.GlowColorEpsilon then return end
    record.glow = glow
    local a, b = MistColours(glow)
    Call("SetParticleAffectorParameter", record.name, 0, "colour1", a)
    Call("SetParticleAffectorParameter", record.name, 0, "colour2", b)
end

-- =============================================================================
-- Ground mist: pools in low ground (map data), streamed around the player
-- =============================================================================

local function StreamSites(sites, live, maxLive, inRange, outRange, create, destroy, playerPos)
    if playerPos == nil then return end

    local count = 0
    local drop = {}
    for index in pairs(live) do
        local site = sites[index]
        local d = site and Distance2D(site.x, site.z, playerPos.x, playerPos.z) or nil
        if d == nil or d > outRange then
            drop[#drop + 1] = index
        else
            count = count + 1
        end
    end
    for i = 1, #drop do
        destroy(drop[i], live[drop[i]])
        live[drop[i]] = nil
    end

    -- One creation per pass, nearest first, so a pass never stalls a frame.
    if count >= maxLive then return end

    local best, bestDistance = nil, inRange
    for index = 1, #sites do
        if live[index] == nil then
            local d = Distance2D(sites[index].x, sites[index].z, playerPos.x, playerPos.z)
            if d < bestDistance then
                best, bestDistance = index, d
            end
        end
    end
    if best ~= nil then
        local record = create(best, sites[best])
        if record ~= nil then live[best] = record end
    end
end

local function PoolRateOf(pool)
    local weight = Clamp(tonumber(pool.weight) or 1.0, 0.0, 1.0)
    return V.PoolRate * (weight ^ V.PoolWeightPower) * V.GetMistScale()
end

local function PoolCreate(_, pool)
    local ground = TerrainHeight(pool.x, pool.z) or 0.0
    local name = Fx_Create("pool", "CR/Moon/GroundMist", pool.x, ground + V.MistHeight, pool.z)
    if name == nil then return nil end
    local record = { name = name, pool = pool, rate = -1.0, glow = nil }
    ApplyMistColour(record, V.GlowLevel)
    record.rate = PoolRateOf(pool)
    Call("SetParticleEmitterEmissionRate", name, 0, record.rate)
    return record
end

local function PoolDestroy(_, record)
    Fx_Destroy(record.name)
end

local function UpdatePoolRates()
    if V.Clock < V.NextPoolAt then return end
    V.NextPoolAt = V.Clock + 1.0
    for _, record in pairs(V.PoolLive) do
        local rate = PoolRateOf(record.pool)
        if math.abs(rate - record.rate) > 0.02 then
            record.rate = rate
            Call("SetParticleEmitterEmissionRate", record.name, 0, rate)
        end
        ApplyMistColour(record, V.GlowLevel)
    end
    local layer = V.LocalLayer
    if layer ~= nil then ApplyMistColour(layer, V.GlowLevel) end
end

function V.GetPools() return V.Pools end


function V.Describe()
    return string.format("mist %.2f (density %.2f) glow %.2f%s systems %d pools %d impacts %d hover %d",
        V.GetMistScale(), V.DensityValue, V.GlowLevel, V.IsGlowing() and " GLOWING" or "",
        V.SystemCount, V.GetLivePoolCount(), V.Stats.impacts, V.Stats.hoverTracked)
end

-- =============================================================================
-- Save / load
--
-- Particle systems do not survive a save; only the director's scalars persist.
-- =============================================================================

function V.Save()
    local scripted = {}
    for i = 1, #V.Scripted do
        local w = V.Scripted[i]
        scripted[i] = {
            id = w.id, remaining = (w.start + w.rise + w.hold + w.fall) - V.Clock,
            ago = V.Clock - w.start, rise = w.rise, hold = w.hold, fall = w.fall, strength = w.strength,
        }
    end
    return {
        seed = V.Seed, clock = V.Clock, density = V.Density, densityValue = V.DensityValue,
        glowSerial = V.GlowSerial, scripted = scripted,
    }
end

function V.Load(state)
    if type(state) ~= "table" then return end
    if not V.Initialized then V.Init() end

    if state.seed ~= nil and (V.Seed ~= state.seed or V.GlowRng == nil) then
        BuildTimeline(state.seed)
        V.Synced = true
    end
    V.Clock = tonumber(state.clock) or 0.0
    V.Density = Clamp(tonumber(state.density) or V.DensityDefault, V.DensityLimit[1], V.DensityLimit[2])
    V.DensityValue = Clamp(tonumber(state.densityValue) or V.Density, V.DensityLimit[1], V.DensityLimit[2])
    V.GlowSerial = tonumber(state.glowSerial) or 0

    V.Scripted = {}
    for _, w in ipairs(state.scripted or {}) do
        if (tonumber(w.remaining) or 0.0) > 0.0 then
            V.Scripted[#V.Scripted + 1] = {
                id = w.id, start = V.Clock - (tonumber(w.ago) or 0.0), rise = tonumber(w.rise) or 0.0,
                hold = tonumber(w.hold) or 0.0, fall = tonumber(w.fall) or 0.0,
                strength = tonumber(w.strength) or 0.0,
            }
        end
    end

    -- Loading rebuilds the Ogre scene: every system we held is already gone.
    Fx_DestroyAll()
    V.PoolLive, V.LocalLayer, V.ImpactPool, V.HoverLive, V.RecentImpacts = {}, nil, {}, {}, {}
    V.NextStreamAt, V.NextLocalAt, V.NextPoolAt, V.NextHoverAt = 0.0, 0.0, 0.0, 0.0
    V.LastStateKey = nil
end


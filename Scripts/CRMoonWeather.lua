-- The mist the weather trends toward: 0 = none, 1 = the authored amount, 2 = thick.
-- Host / offline only; a guest ignores it because the host's state carries it.
function V.SetDensity(scale)
    if not V.IsAuthority then return V.Density end
    V.Density = Clamp(tonumber(scale) or V.DensityDefault, V.DensityLimit[1], V.DensityLimit[2])
    BroadcastState(true)
    return V.Density
end

-- Live tuning from the Lua console: CRMoonWeather.Tune("MistHeight", 1.2).
function V.Tune(name, value)
    if type(name) ~= "string" or V[name] == nil or type(V[name]) == "function" then return false end
    if type(V[name]) ~= type(value) then return false end
    V[name] = value
    -- Force the layers to re-evaluate what depends on it.
    V.NextLocalAt, V.NextPoolAt = 0.0, 0.0
    if V.LocalLayer ~= nil then V.LocalLayer.glow = nil end
    for _, record in pairs(V.PoolLive) do record.glow = nil end
    return true
end


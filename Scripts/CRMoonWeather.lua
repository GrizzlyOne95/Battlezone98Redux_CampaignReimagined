end

-- =============================================================================
-- Ground mist: the layer that follows the player
-- =============================================================================

-- Thirteen patch offsets: a centre cell, an inner ring of six and an outer ring
-- of six rotated 30 degrees, so the outer cells sit in the gaps of the inner ring.
local function PatchOffsets()
    local offsets = { { x = 0.0, z = 0.0, ring = 0 } }
    for k = 0, 5 do
        local a = math.rad(k * 60.0)
        offsets[#offsets + 1] = { x = math.cos(a) * V.LocalInnerRadius, z = math.sin(a) * V.LocalInnerRadius, ring = 1 }
    end
    for k = 0, 5 do
        local a = math.rad(30.0 + (k * 60.0))
        offsets[#offsets + 1] = { x = math.cos(a) * V.LocalOuterRadius, z = math.sin(a) * V.LocalOuterRadius, ring = 2 }
    end
    return offsets
end

local function SmoothFlat(slope)
    local span = math.max(0.01, V.LocalSlopeEnd - V.LocalSlopeStart)
    return 1.0 - SmoothStep((slope - V.LocalSlopeStart) / span)
end

local function UpdateLocalMist()
    if not (V.TemplatesReady and V.AllowLocalMist and V.AllowGroundMist) then return end
    if V.Clock < V.NextLocalAt then return end
    V.NextLocalAt = V.Clock + V.LocalInterval

    local p = LocalPlayerPosition()
    if p == nil then return end
    local ground = TerrainHeight(p.x, p.z)
    if ground == nil then return end

    local layer = V.LocalLayer
    if layer == nil then
        local name = Fx_Create("local", "CR/Moon/LocalMist", p.x, ground, p.z)
        if name == nil then return end
        layer = { name = name, rates = {}, patches = {}, glow = nil, offsets = PatchOffsets() }
        V.LocalLayer = layer
        for i = 1, #layer.offsets do Call("SetParticleEmitterEmissionRate", name, i - 1, 0.0) end
        ApplyMistColour(layer, V.GlowLevel)
    else
        Call("SetParticleSystemPosition", layer.name, Vec(p.x, ground, p.z))
    end

    -- Sample the ground under every patch.
    local samples, sum, count = {}, 0.0, 0
    for i = 1, #layer.offsets do
        local o = layer.offsets[i]
        local h, normal = TerrainSample(p.x + o.x, p.z + o.z)
        samples[i] = { h = h, slope = SlopeDegrees(normal) }
        if h ~= nil then sum = sum + h; count = count + 1 end
    end
    if count == 0 then return end

    -- The surroundings: a ring of samples well outside the patches. A patch is
    -- "low" if it lies below that ring (a bowl, a crater floor) and "high" if it
    -- lies above it (a ridge, a hilltop). Comparing patches only with each other
    -- would just move mist between them: their depths sum to zero by construction.
    local ringSum, ringCount = 0.0, 0
    for k = 0, 7 do
        local a = math.rad(k * 45.0)
        local h = TerrainHeight(p.x + (math.cos(a) * V.LocalReferenceRadius), p.z + (math.sin(a) * V.LocalReferenceRadius))
        if h ~= nil then ringSum = ringSum + h; ringCount = ringCount + 1 end
    end
    local average = (ringCount > 0) and (ringSum / ringCount) or (sum / count)
    local scale = V.GetMistScale()

    for i = 1, #layer.offsets do
        local o, s = layer.offsets[i], samples[i]
        local weight = 0.0
        if s.h ~= nil then
            local depth = average - s.h   -- positive: this patch is lower than its neighbours
            weight = SmoothFlat(s.slope) * Clamp(V.LocalBaseWeight + (depth / V.LocalDepthForFull), 0.0, 1.0)
            Call("SetParticleEmitterPosition", layer.name, i - 1, Vec(o.x, (s.h - ground) + V.MistHeight, o.z))
        end
        local ringScale = (o.ring == 2) and V.LocalOuterRateScale or 1.0
        local rate = V.LocalRate * weight * ringScale * scale
        layer.patches[i] = { weight = weight, height = s.h, slope = s.slope, rate = rate }
        if math.abs(rate - (layer.rates[i] or -1.0)) > 0.03 then
            layer.rates[i] = rate
            Call("SetParticleEmitterEmissionRate", layer.name, i - 1, rate)
        end
    end
    V.Stats.localUpdates = V.Stats.localUpdates + 1
end

function V.GetLocalPatches()
    return V.LocalLayer and V.LocalLayer.patches or {}
end

-- =============================================================================
-- Impact dust: chained exu.BulletHit, a pooled puff
-- =============================================================================

local function AcquireImpactSlot()
    local oldest, oldestAt = nil, math.huge
    for i = 1, V.MaxImpactSystems do
        local slot = V.ImpactPool[i]
        if slot == nil or not slot.created then
            return i
        end
        if slot.busyUntil <= V.Clock then return i end
        if slot.busyUntil < oldestAt then oldest, oldestAt = i, slot.busyUntil end
    end
    return oldest
end

-- A puff of dust where something struck the ground. Local and cosmetic; every
-- peer decides it for itself from its own ordnance callbacks.
function V.NotifyImpact(x, y, z)
    if not (V.Initialized and V.Enabled and V.AllowImpactDust and V.TemplatesReady) then return false end
    if type(x) ~= "number" or type(y) ~= "number" or type(z) ~= "number" then return false end

    local p = LocalPlayerPosition()
    if p ~= nil and Distance2D(x, z, p.x, p.z) > V.ImpactRange then
        V.Stats.impactsSkipped = V.Stats.impactsSkipped + 1
        return false
    end

    local ground = TerrainHeight(x, z)
    if ground == nil or (y - ground) > V.ImpactMaxHeight then
        V.Stats.impactsSkipped = V.Stats.impactsSkipped + 1
        return false
    end

    if (V.Clock - V.LastImpactAt) < V.ImpactMinInterval then
        V.Stats.impactsSkipped = V.Stats.impactsSkipped + 1
        return false
    end
    for i = #V.RecentImpacts, 1, -1 do
        local r = V.RecentImpacts[i]
        if (V.Clock - r.at) > V.ImpactSpotSeconds then
            table.remove(V.RecentImpacts, i)
        elseif Distance2D(x, z, r.x, r.z) < V.ImpactSpotRadius then
            V.Stats.impactsSkipped = V.Stats.impactsSkipped + 1
            return false
        end
    end

    local index = AcquireImpactSlot()
    if index == nil then return false end
    local slot = V.ImpactPool[index]
    if slot == nil then
        slot = { name = nil, created = false, busyUntil = 0.0 }
        V.ImpactPool[index] = slot
    end
    if not slot.created then
        local name = Fx_Create("kick", "CR/Moon/KickDust", x, ground + V.ImpactLift, z)
        if name == nil then return false end
        slot.name = name
        slot.created = true
    end

    Call("SetParticleSystemPosition", slot.name, Vec(x, ground + V.ImpactLift, z))
    Call("SetParticleEmitterEmissionRate", slot.name, 0, V.ImpactRate * V.Quality)
    slot.busyUntil = V.Clock + V.ImpactBurstSeconds
    slot.firing = true
    V.LastImpactAt = V.Clock
    V.RecentImpacts[#V.RecentImpacts + 1] = { x = x, z = z, at = V.Clock }
    V.Stats.impacts = V.Stats.impacts + 1
    return true
end

local function UpdateImpactPool()
    for i = 1, V.MaxImpactSystems do
        local slot = V.ImpactPool[i]
        if slot ~= nil and slot.created and slot.firing and slot.busyUntil <= V.Clock then
            slot.firing = false
            Call("SetParticleEmitterEmissionRate", slot.name, 0, 0.0)
        end
    end
end

local function OnBulletHit(_, _, _, transform)
    if type(transform) ~= "table" then return end
    local x = transform.posit_x or transform.x
    local y = transform.posit_y or transform.y
    local z = transform.posit_z or transform.z
    V.NotifyImpact(x, y, z)
end

-- exu.BulletHit is a single global that other modules (PhysicsImpact, CRReactive)
-- also use, so chain rather than replace: whatever was there runs first, unchanged.
local function InstallHooks()
    if V.HooksInstalled or type(exu) ~= "table" then return end
    V.ChainedHit = exu.BulletHit
    V.HitWrapper = function(odf, shooter, hitObject, transform, ordnanceHandle)
        if V.ChainedHit ~= nil then
            pcall(V.ChainedHit, odf, shooter, hitObject, transform, ordnanceHandle)
        end
        if V.Initialized then
            local ok, err = pcall(OnBulletHit, odf, shooter, hitObject, transform, ordnanceHandle)
            if not ok then Log("OnBulletHit failed: " .. tostring(err)) end
        end
    end
    exu.BulletHit = V.HitWrapper
    V.HooksInstalled = true
end

-- Put the previous handler back if ours is still on top. If something chained on
-- top of us, leave the chain alone: our wrapper is inert once Initialized is false.
local function RemoveHooks()
    if not V.HooksInstalled then return end
    if exu.BulletHit == V.HitWrapper then
        exu.BulletHit = V.ChainedHit
        V.HooksInstalled = false
        V.HitWrapper = nil
    end
end

-- =============================================================================
-- Hover dust: under low, moving craft
-- =============================================================================

local function CraftIterator()
    if type(AllCraft) ~= "function" then return nil end
    local ok, iterator = pcall(AllCraft)
    if ok and type(iterator) == "function" then return iterator end
    return nil
end

-- movedAgo: seconds since the craft last moved faster than HoverMinSpeed. A
-- craft that has never moved (a gun tower that counts as a craft) emits nothing.
local function HoverRateOf(speed, height, movedAgo)
    if height > V.HoverMaxHeight then return 0.0 end
    local near = 1.0 - Clamp(height / V.HoverMaxHeight, 0.0, 1.0)
    local rate = 0.0
    if speed >= V.HoverMinSpeed then
        rate = V.HoverRate * Clamp(speed / V.HoverFullSpeed, 0.1, 1.0) * (0.35 + (0.65 * near))
    elseif height <= V.HoverIdleMaxHeight and movedAgo <= V.HoverIdleGrace then
        rate = V.HoverRate * V.HoverIdleShare * near
    end
    return rate * V.Quality
end

local function UpdateHoverDust()
    if not (V.TemplatesReady and V.AllowHoverDust) then return end
    if V.Clock < V.NextHoverAt then return end
    V.NextHoverAt = V.Clock + V.HoverInterval

    local p = LocalPlayerPosition()
    local iterator = CraftIterator()
    if p == nil or iterator == nil or type(GetVelocity) ~= "function" then return end

    -- Candidates: craft near the player that are low enough to disturb the ground.
    local candidates = {}
    for h in iterator do
        if ValidHandle(h) then
            local pos = PositionOf(h)
            if pos ~= nil then
                local d = Distance2D(pos.x, pos.z, p.x, p.z)
                if d <= V.HoverTrackRange then
                    local ground = TerrainHeight(pos.x, pos.z)
                    local okv, velocity = pcall(GetVelocity, h)
                    if ground ~= nil and okv and type(velocity) == "table" then
                        local speed = math.sqrt(((velocity.x or 0.0) ^ 2) + ((velocity.z or 0.0) ^ 2))
                        local height = pos.y - ground
                        if speed >= V.HoverMinSpeed then V.HoverMoved[h] = V.Clock end
                        local rate = HoverRateOf(speed, height, V.Clock - (V.HoverMoved[h] or -1000.0))
                        if rate > 0.01 then
                            candidates[#candidates + 1] = {
                                h = h, d = d, x = pos.x, z = pos.z, ground = ground, rate = rate,
                            }
                        end
                    end
                end
            end
        end
    end
    table.sort(candidates, function(a, b)
        if a.d ~= b.d then return a.d < b.d end
        return tostring(a.h) < tostring(b.h)
    end)

    local active = {}
    for i = 1, math.min(#candidates, V.MaxHoverSystems) do
        local c = candidates[i]
        active[c.h] = true
        local record = V.HoverLive[c.h]
        if record == nil then
            local name = Fx_Create("hover", "CR/Moon/HoverDust", c.x, c.ground + 0.2, c.z)
            if name ~= nil then
                record = { name = name, rate = 0.0, idleSince = nil }
                V.HoverLive[c.h] = record
                V.Stats.hoverTracked = V.Stats.hoverTracked + 1
            end
        end
        if record ~= nil then
            Call("SetParticleSystemPosition", record.name, Vec(c.x, c.ground + 0.2, c.z))
            if math.abs(c.rate - record.rate) > 0.5 then
                record.rate = c.rate
                Call("SetParticleEmitterEmissionRate", record.name, 0, c.rate)
            end
            record.idleSince = nil
        end
    end

    -- Craft that stopped qualifying go quiet, then lose their system.
    local drop = {}
    for h, record in pairs(V.HoverLive) do
        if not active[h] then
            if record.rate > 0.0 then
                record.rate = 0.0
                Call("SetParticleEmitterEmissionRate", record.name, 0, 0.0)
            end
            record.idleSince = record.idleSince or V.Clock
            if (V.Clock - record.idleSince) >= V.HoverLinger or not ValidHandle(h) then
                drop[#drop + 1] = h
            end
        end
    end
    for i = 1, #drop do
        Fx_Destroy(V.HoverLive[drop[i]].name)
        V.HoverLive[drop[i]] = nil
    end

    -- Forget craft that have not moved for a long while (or are gone).
    for h, at in pairs(V.HoverMoved) do
        if (V.Clock - at) > (V.HoverIdleGrace * 5.0) or not ValidHandle(h) then V.HoverMoved[h] = nil end
    end
end

-- =============================================================================
-- Environment contribution (ambient lift only; fog, sun and diffuse untouched)
-- =============================================================================

local function EnvironmentModifier(frame)
    if not (V.Enabled and V.AllowEnvironmentGlow) then return end
    local glow = V.GlowLevel
    if glow > 0.001 and frame.ambient then
        local c = V.GlowAmbient
        frame.ambient.r = frame.ambient.r + (c.r * glow)
        frame.ambient.g = frame.ambient.g + (c.g * glow)
        frame.ambient.b = frame.ambient.b + (c.b * glow)
    end
end

V.EnvironmentModifier = EnvironmentModifier


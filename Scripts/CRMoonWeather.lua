-- CRMoonWeather.lua
-- Moon weather and atmosphere director for Campaign Reimagined (first users:
-- misn02b "Red Arrival" and misn03 "Eagle's Nest"). Reusable by any Moon mission.
--
-- The Moon is airless, so there is no wind, no cloud, no rain and no storm. The
-- look this director draws is the one in the owner's concept art: a black sky and
-- a crisp Earth over a dark surface, with a pale grey-blue mist lying ONLY along
-- the ground -- knee to waist high on a soldier -- fading out over the surface,
-- rocks poking through it. Physically that is a defensible picture of the real
-- thing: electrostatically levitated dust (Surveyor's "horizon glow") and
-- regolith kicked up in 1/6 g, which hangs and settles slowly. Nothing dramatic.
--
--   ground mist   thin, slow, flat (horizontal) cards on the ground. Two parts:
--                   * POOLS in low ground (crater floors, basins) from map data
--                     generated by Tools/Build-MoonSites.py, streamed in around
--                     the player;
--                   * a LOCAL layer that follows the player: 13 small emitters
--                     put on sampled terrain patches a couple of times a second,
--                     denser over low ground, thinner over ridges and slopes.
--   glow          rare, slow periods (minutes apart) when the mist thickens a
--                 little and catches more light: a seeded timeline every peer
--                 computes identically, plus host-scripted glows. Expressed in
--                 the mist itself (rate and colour); when Environment.lua is
--                 loaded it also lends a tiny ambient lift. Fog is NEVER touched.
--   impact dust   a pooled puff where ordnance strikes ground (a chained
--                 exu.BulletHit): thrown up, hangs, settles. Local and cosmetic.
--   hover dust    fine dust under low, moving craft (player and the nearest few).
--
-- WHY THE GLOBAL FOG IS NOT TOUCHED. Both Moon missions keep the map's own
-- atmosphere (fog 175-250, black sky). In DX11 Enhanced the authored fog range
-- also scales terrain diffuse IBL (Docs/DX11_FOG_LUNAR_ART_DIRECTION_RECONSTRUCTION.md),
-- so raising global fog to get a mist would wash the terrain and grey the sky.
-- The mist is therefore ground-hugging particles only. The director registers an
-- Environment modifier ONLY if Environment.lua is loaded, and that modifier only
-- adds a very small ambient lift during a glow; it never edits fog, sun or
-- diffuse, and never calls an exu fog / light function itself. The two Moon
-- missions do not load Environment (loading it would start its day/night cycle
-- and night sensor nerf on a map that has neither), so there the glow lives in
-- the particles alone.
--
-- GAMEPLAY EFFECTS: NONE. It never damages, shoves, slows, spawns, removes,
-- retargets or re-teams anything, never touches AI perception, sensors, radar,
-- cloaks or objectives, and registers no Environment gameplay modifier. The only
-- state it writes is particle systems (and, if present, the Environment ambient
-- lift). It READS positions, velocities and terrain height. It plays no sound
-- (vacuum). The one global it hooks is exu.BulletHit, by chaining: the previous
-- handler always runs first and unchanged. Tools/Test-CRMoonWeather.lua audits
-- every BZ and exu function the module calls against an allowlist.
--
-- CO-OP. The Io/Europa hybrid, smaller:
--   * Glow timing is a pure function of a SEED (Park-Miller streams from
--     CRVenusMap, no math.random). The host announces seed + clock + density
--     (MoonState) at start, on change and every NetHeartbeat seconds; a guest
--     adopts the seed and corrects its clock when it drifts more than 2 s.
--   * A host-scripted glow (Glow()) is one numeric event (MoonGlow) every peer
--     renders at once. A guest's call is ignored.
--   * The mist itself, impact dust and hover dust are local, from static map
--     data and the peer's own terrain / craft; they only have to look right on
--     that screen. The breathing of the mist density is a function of the clock
--     and seed, so it cannot desynchronise a stream (no random draws).
--
-- PUBLIC API (host / offline unless noted; a guest's call is ignored)
--   Init{ authority, seed, send, sites, enabled, debug, quality, density,
--         groundMist, localMist, glow, randomGlow, impactDust, hoverDust,
--         environmentGlow }
--   Update(dt)                every frame, every peer
--   Shutdown()                destroys systems, unregisters the modifier, unhooks
--   Save() / Load(state)      director scalars (systems do not survive a save)
--   SetDensity(scale, ...)    0..2, the mist the timeline trends toward (1 = normal)
--   Glow(duration, strength)  one glow now (4..300 s, 0..1)
--   NotifyImpact(x, y, z)     a puff of impact dust (also what exu.BulletHit calls)
--   AnnounceState()           re-send MoonState (host; call once the session is ready)
--   ApplyNetEvent(op, ...)    guest receive path, true when handled; host ignores
--   GetNetState() / ApplyNetState(...) / SetNetwork{send, authority}
--   OnObjectCreated(h)        present for adapters that forward every object
--   Tune(name, value)         override a tunable at run time (live tuning)
--   getters: GetGlow IsGlowing GetDensity GetMistScale GetBreath GetPools
--            GetLivePoolCount GetGlowWindows GetStats GetSystemCount GetLocalPatches
--            Describe
-- Wire ops (all arguments numbers): MoonState, MoonGlow. See Docs/MOON_WEATHER.md.


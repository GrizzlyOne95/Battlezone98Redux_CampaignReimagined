-- Ends any shake at once (a cutscene, a mission end). Local to this peer.
function V.StopQuake()
    NativeStopQuake(false)
    if V.Quake_ ~= nil then
        V.Quake_ = nil
        V.LastQuakeEndAt = V.Clock
    end
    DestroyQuakeFx()
end

-- =============================================================================
-- Radiation surges (Jupiter's plasma) -- VISUAL ONLY
-- =============================================================================

local function SurgeEnvelopeAt(s, age)
    return EnvelopeAt(s.duration, V.SurgeRise, V.SurgeFall, age, 0.2, 0.6)
end

-- A deterministic shimmer in 0..1 from the clock alone: the sum of two
-- incommensurate sines, so it never repeats audibly and needs no random draw
-- (a peer that draws no random numbers cannot desynchronise the streams).
local function Flicker(t)
    return 0.5 + (0.25 * math.sin(t * 17.0)) + (0.25 * math.sin((t * 41.0) + 1.3))
end

-- 0 with no surge; otherwise strength x envelope (0..1), without the flicker.
function V.GetSurgeIntensity()
    local s = V.Surge_
    if s == nil then return 0.0 end
    return s.strength * SurgeEnvelopeAt(s, V.Clock - s.start)
end

function V.BeginSurge(id, strength, duration, kind)
    if not V.AllowSurges then return false end
    strength = Clamp(tonumber(strength) or 0.0, 0.0, 1.0)
    duration = Clamp(tonumber(duration) or 0.0, V.SurgeDurationLimit[1], V.SurgeDurationLimit[2])
    if strength < 0.05 then return false end
    id = tonumber(id)
    if id ~= nil then
        if V.SeenSurges[id] then return false end
        V.SeenSurges[id] = true
        V.SeenSurges[id - 200] = nil
    end
    kind = tonumber(kind) or 1

    V.Stats.surges = V.Stats.surges + 1
    if kind == 2 then V.Stats.randomSurges = V.Stats.randomSurges + 1
    else V.Stats.scriptedSurges = V.Stats.scriptedSurges + 1 end
    if strength > V.Stats.peakSurge then V.Stats.peakSurge = strength end
    V.SurgeLog[#V.SurgeLog + 1] = { id = id, strength = strength, duration = duration, kind = kind, at = V.Clock }
    if #V.SurgeLog > 64 then table.remove(V.SurgeLog, 1) end

    local s = V.Surge_
    if s ~= nil and (V.Clock - s.start) < s.duration then
        s.strength = math.max(s.strength, strength)
        s.duration = math.max(s.duration, (V.Clock - s.start) + duration)
        V.Stats.mergedSurges = V.Stats.mergedSurges + 1
    else
        V.Surge_ = { id = id, strength = strength, start = V.Clock, duration = duration, kind = kind }
        PlayLocalSound(V.SurgeSound, V.SurgeSoundVolume * Clamp(strength, 0.3, 1.0), 120)
    end
    return true
end

-- Host / offline: one surge now. duration seconds (0.5..20), strength 0..1.
function V.Surge(duration, strength)
    if not V.Initialized then V.Init() end
    if not V.IsAuthority or not V.AllowSurges then return false end
    duration = Clamp(tonumber(duration) or V.SurgeScriptedDefault[2], V.SurgeDurationLimit[1], V.SurgeDurationLimit[2])
    strength = Clamp(tonumber(strength) or V.SurgeScriptedDefault[1], V.SurgeScriptedRange[1], V.SurgeScriptedRange[2])
    V.SurgeSerial = V.SurgeSerial + 1
    local id = V.SurgeSerial
    if not V.BeginSurge(id, strength, duration, 1) then return false end
    Send("EuropaSurge", id, strength, duration, 1)
    return true
end

local function ScheduleNextSurge()
    local scale = math.max(0.1, LadderValue("surgeScale"))
    V.NextSurgeAt = V.Clock + (V.SurgeRng.Range(V.SurgeGap[1], V.SurgeGap[2]) / scale)
end

local function UpdateRandomSurges()
    if not (V.IsAuthority and V.Synced and V.AllowSurges and V.AllowRandomSurges) then return end
    if V.Clock < V.NextSurgeAt then return end

    if V.Surge_ ~= nil or (V.Clock - V.LastSurgeEndAt) < V.SurgeMinSpacing then
        V.NextSurgeAt = V.Clock + 5.0
        return
    end

    local rng = V.SurgeRng
    local strength = rng.Range(V.SurgeStrength[1], V.SurgeStrength[2])
    local duration = rng.Range(V.SurgeDuration[1], V.SurgeDuration[2])
    ScheduleNextSurge()
    V.SurgeSerial = V.SurgeSerial + 1
    local id = V.SurgeSerial
    if V.BeginSurge(id, strength, duration, 2) then
        Send("EuropaSurge", id, strength, duration, 2)
    end
end

local function DestroySurgeFx()
    if V.SurgeFx ~= nil then
        Fx_Destroy(V.SurgeFx.name)
        V.SurgeFx = nil
    end
end

local function UpdateSurge()
    local s = V.Surge_
    if s == nil then
        if V.SurgeFx ~= nil and V.Clock >= V.SurgeFx.until_ then DestroySurgeFx() end
        return
    end

    local age = V.Clock - s.start
    if age >= s.duration then
        V.Surge_ = nil
        V.LastSurgeEndAt = V.Clock
        if V.SurgeFx ~= nil then
            Call("SetParticleEmitterEmissionRate", V.SurgeFx.name, 0, 0.0)
            V.SurgeFx.until_ = V.Clock + V.SurgeMoteLinger
        end
        return
    end

    if V.AllowAurora and V.TemplatesReady then
        if V.SurgeFx == nil then
            local name = Fx_Create("surge", "CR/Europa/SurgeMotes", 0.0, 0.0, 0.0)
            if name ~= nil then
                Call("AttachParticleSystemToCamera", name, Vec(0.0, 40.0, 0.0))
                V.SurgeFx = { name = name, rate = -1.0, until_ = math.huge }
            end
        end
        if V.SurgeFx ~= nil then
            V.SurgeFx.until_ = math.huge
            local rate = V.SurgeMoteRate * V.GetSurgeIntensity()
            if math.abs(rate - V.SurgeFx.rate) > 1.5 then
                V.SurgeFx.rate = rate
                Call("SetParticleEmitterEmissionRate", V.SurgeFx.name, 0, rate)
            end
        end
    end
end

function V.IsSurging() return V.Surge_ ~= nil end
function V.GetSurge()
    local s = V.Surge_
    if s == nil then return nil end
    return { strength = s.strength, duration = s.duration, elapsed = V.Clock - s.start, kind = s.kind }
end


local function PlumeWisp(site)
    return site.major and V.PlumeMajorWisp or V.PlumeMinorWisp
end

local function PlumeCreate(index, site)
    local y = GroundY(site)
    local name = Fx_Create("plume", "CR/Europa/Plume", site.x, y + 1.0, site.z)
    if name == nil then return nil end

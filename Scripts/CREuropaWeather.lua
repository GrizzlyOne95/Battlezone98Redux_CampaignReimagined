-- CREuropaWeather.lua
-- Europa weather and atmosphere director for Campaign Reimagined (first user:
-- misn12 "Flying Solo", the stealth infiltration). Reusable by any Europa mission.
--
-- Europa has essentially no atmosphere -- a tenuous oxygen exosphere and nothing
-- more -- so there is NO wind-driven blizzard, cloud or rain here. What the place
-- really has is:
--
--   * cryovolcanic water-vapour plumes at its geysers (the BZN's eggeizr1
--     objects). Vapour thrown up ballistically freezes and falls back as fine ice
--     crystals, straight down (no wind), around the vent;
--   * tidal ice quakes, because Jupiter flexes the shell every 3.55 days;
--   * Jupiter's radiation and plasma surges, drawn as a brief violet-green
--     auroral glow and a flicker in the light;
--   * a low sublimation frost haze over frosted ground between the events.
--
-- Parts (same architecture as CRIoWeather / CRVenusWeather / CRMarsWeather):
--
--   ladder     five ACTIVITY rungs -- quiescent, stirring, venting, flexing,
--              perijove -- as a seeded timeline (CRVenusMap.NewLadder) with
--              temporary intense EPISODES. The smoothed fractional position
--              drives everything continuous; integer rungs select a CRWeather
--              preset. It sets the event rates (plumes, quakes, surges).
--   presets    five Europa* CRWeather presets (registered at Init; the shared
--              CRWeatherPresets.lua is not edited): cold pale fog, Jupiter-lit
--              ambient, and a sparse ice glitter falling STRAIGHT down.
--   plumes     a vapour column at each vent site, host-scheduled and replicated,
--              with ice fall (CR/Europa/IceFall) and a local frost haze that
--              briefly thins the view near the vent.
--   quakes     the stock StartEarthquake / UpdateEarthQuake / StopEarthquake
--              natives on an envelope, plus camera-attached ice dust. Rare,
--              gentle, host-decided. A strong quake can crack a vent open.
--   surges     Jupiter radiation surges: Environment tint + light flicker +
--              sparse additive motes + a crackle. VISUAL ONLY (see below).
--   frost      CR/Europa/FrostHaze sheets streamed in over frosted ground
--              (anchors generated by Tools/Build-EuropaSites.py).
--
-- GAMEPLAY EFFECTS: NONE. The director never damages, shoves, scrambles, slows,
-- spawns, removes, retargets or re-teams anything, never touches AI perception,
-- sensors, radar, cloaks or stealth, and registers no Environment gameplay
-- modifier. A surge is NOT radar/HUD interference: reducing radar range or
-- jamming velocity is a per-craft sensor change that AI units share, so it could
-- change what is detected in a stealth mission. The only world state it writes
-- is render state: the CRWeather preset, an Environment (fog / light) modifier,
-- particle systems, local 2D sounds and the engine's earthquake shake.
--
-- CO-OP. The Io hybrid:
--   * The activity timeline is a pure function of a seed; the host announces the
--     seed and its rung (EuropaState) on change and as a heartbeat, and a guest
--     follows that rung for HostOverrideSeconds before falling back to the seeded
--     timeline it has been computing all along.
--   * Plumes, quakes and surges are decided ONLY by the host and sent as one small
--     numeric event each; every peer renders and shakes on receipt. A guest never
--     schedules one of its own.
--   * Frost haze, ice glitter, tint and fog are local, from static map data.
--
-- PUBLIC API (host / offline unless noted; a guest's call is ignored)
--   Init{ authority, seed, send, sites, startLevel, targetLevel, enabled, debug,
--         quality, baseSky, plumes, iceFall, frostHaze, ventHaze, quakes,
--         randomQuakes, quakeIce, surges, randomSurges, aurora, episodes }
--   Update(dt)                      every frame, every peer
--   Shutdown()                      stops the shake, destroys systems
--   Save() / Load(state)            director scalars (systems do not survive a save)
--   SetTargetLevel(n)               level the timeline trends toward (1..5)
--   ForceLevel(n, seconds, transition) / ReleaseForcedLevel()
--   Quake(strength, duration)       one ice quake now (0..1, 0.5..30 s)
--   TriggerPlume(siteIndex, power)  one plume now (alias TriggerEruption)
--   Surge(duration, strength)       one radiation surge now (0.5..20 s)
--   StopQuake()                     end this peer's shake now
--   AnnounceState()                 re-send EuropaState (call when the session is ready)
--   ApplyNetEvent(op, ...)          guest receive path; true when handled
--   GetNetState() / ApplyNetState(...) / SetNetwork{send, authority}
--   OnObjectCreated(h)              forwards to CRWeather
--   getters: GetLevel GetLevelName GetTargetLevel IsEpisode GetSeverity
--            GetVentSites GetFrostPools GetActivePlumes GetStats GetSystemCount
--            IsQuaking GetQuake GetQuakeIntensity IsSurging GetSurge
--            GetSurgeIntensity GetTidalPhase GetVentHaze Describe
-- Wire ops (all arguments numbers): EuropaState, EuropaPlume, EuropaQuake,
-- EuropaSurge. See Docs/EUROPA_WEATHER.md.
--
-- Ownership rules (same as the other weather directors):
--   * Fog, ambient and sun belong to Environment.lua. We set a CRWeather preset
--     and register an Environment modifier; we never call exu.SetFog and friends.
--   * Nothing in this file calls anything that changes health, ammo, velocity,
--     position, teams, targets, sensors or perception.


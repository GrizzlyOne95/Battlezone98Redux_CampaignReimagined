-- Everything a peer needs to rebuild the same weather: seven numbers.
function V.GetNetState()
    local forcedFor = 0.0
    if V.ForcedLevel ~= nil and V.ForcedUntil ~= nil then
        forcedFor = math.max(0.0, V.ForcedUntil - V.Clock)
    end
    return V.Seed or 0, V.Clock, V.Level, V.Episode and 1 or 0, V.TargetLevel,
        V.ForcedLevel or 0, forcedFor
end

function V.ApplyNetState(seed, clock, level, episode, target, forcedLevel, forcedFor)
    seed = tonumber(seed)
    if seed == nil or seed <= 0 then return false end

    if V.Seed ~= seed or V.Ladder == nil then
        BuildLadder(seed)
        V.Clock = tonumber(clock) or V.Clock
        V.Synced = true
    end

    clock = tonumber(clock) or V.Clock
    if math.abs(clock - V.Clock) > 2.0 then V.Clock = clock end

    V.TargetLevel = Clamp(tonumber(target) or V.TargetLevel, 1, LEVEL_COUNT)
    forcedLevel = tonumber(forcedLevel) or 0
    forcedFor = tonumber(forcedFor) or 0
    if forcedLevel > 0 and forcedFor > 0 then
        V.ForcedLevel = Clamp(forcedLevel, 1, LEVEL_COUNT)
        V.ForcedUntil = V.Clock + forcedFor
    elseif not V.IsAuthority then
        V.ForcedLevel = nil
        V.ForcedUntil = nil
    end

    if not V.IsAuthority then
        V.HostOverride = {
            level = Clamp(tonumber(level) or 1, 1, LEVEL_COUNT),
            episode = tonumber(episode) == 1,
            expires = V.Clock + V.HostOverrideSeconds,
        }
    end
    return true
end

-- Dispatch for the mission adapter's receive path. Returns true when handled.
function V.ApplyNetEvent(op, ...)
    if op == "EuropaState" then
        return V.ApplyNetState(...)
    elseif op == "EuropaPlume" then
        if V.IsAuthority then return true end
        return V.BeginPlume(...)
    elseif op == "EuropaQuake" then
        if V.IsAuthority then return true end
        return V.BeginQuake(...)
    elseif op == "EuropaSurge" then
        if V.IsAuthority then return true end
        return V.BeginSurge(...)
    end
    return false
end

local function StateKey()
    return (V.Level * 1) + (V.Episode and 10 or 0) + (V.TargetLevel * 100) + ((V.ForcedLevel or 0) * 1000)
end

local function BroadcastState(force)
    if not V.IsAuthority or V.NetSend == nil then return end
    local key = StateKey()
    if force or key ~= V.LastStateKey or V.Clock >= V.NextNetStateAt then
        V.LastStateKey = key
        V.NextNetStateAt = V.Clock + V.NetHeartbeat
        Send("EuropaState", V.GetNetState())
    end
end

-- The host re-announces on demand: call this when a guest reports it is ready,
-- so a guest that initialised after the first announcement is not left on calm
-- weather until the next heartbeat.
function V.AnnounceState()
    BroadcastState(true)
end

function V.SetNetwork(options)
    options = options or {}
    if options.send ~= nil then V.NetSend = options.send end
    if options.authority ~= nil then V.IsAuthority = options.authority and true or false end
end

-- =============================================================================
-- Lifecycle
-- =============================================================================

-- options:
--   seed            number; the host's. Guests in a network game omit it and wait
--                   for the host's EuropaState.
--   authority       true on the host / offline, false on a guest
--   send            function(op, ...) -- delivers an EuropaState / EuropaPlume /
--                   EuropaQuake / EuropaSurge event to every guest (host only)
--   sites           the generated CREuropaSites table (vents, frost anchors)
--   startLevel, targetLevel
--   enabled, debug, quality, baseSky     passthrough
--   plumes, iceFall, frostHaze, ventHaze, quakes, randomQuakes, quakeIce,
--   surges, randomSurges, aurora, episodes, sounds
--                   sub-system switches
function V.Init(options)
    if V.Initialized then return end
    options = options or {}

    if options.enabled ~= nil then V.Enabled = options.enabled and true or false end
    if options.debug ~= nil then V.Debug = options.debug and true or false end
    local switches = {
        plumes = "AllowPlumes", iceFall = "AllowIceFall", frostHaze = "AllowFrostHaze",
        ventHaze = "AllowVentHaze", quakes = "AllowQuakes", randomQuakes = "AllowRandomQuakes",
        quakeIce = "AllowQuakeIce", surges = "AllowSurges", randomSurges = "AllowRandomSurges",
        aurora = "AllowAurora", episodes = "AllowEpisodes", sounds = "AllowSounds",
        glassSnow = "AllowGlassSnow",
    }
    for key, field in pairs(switches) do
        if options[key] ~= nil then V[field] = options[key] and true or false end
    end

    V.SetNetwork({ send = options.send, authority = options.authority })

    V.RegisterPresets()
    CRWeather.Init({
        enabled = V.Enabled,
        quality = options.quality,
        debug   = options.debug,
        baseSky = options.baseSky,
    })

    -- Vehicle wakes: render-only debris under low, moving craft near the viewer
    -- (shared CRWake module). options.vehicleWakes = false switches them off.
    pcall(Wake.Init, {
        surface = "ice", enabled = options.vehicleWakes ~= false, quality = options.quality,
        debug = options.debug,
    })

    -- Our particle templates are an opt-in payload, so a build that has not
    -- shipped it degrades to presets + quakes rather than failing weather.
    V.TemplatesReady = false
    local okTemplates, templates = pcall(require, "CRParticleTemplates")
    if okTemplates and type(templates) == "table" and type(templates.EnsureExtra) == "function" then
        local ready, reason = templates.EnsureExtra("cr_europa")
        V.TemplatesReady = ready and true or false
        if not ready then
            print("CREuropaWeather: cr_europa particle templates unavailable (" .. tostring(reason) ..
                "); plumes, ice fall, frost haze, quake ice and surge motes are off")
        end
    end

    V.Clock = 0.0
    V.LastRealTime = nil
    V.GlassSnow = 0.0
    V.TargetLevel = Clamp(tonumber(options.targetLevel) or 2, 1, LEVEL_COUNT)
    V.ForcedLevel = nil
    V.ForcedUntil = nil
    V.HostOverride = nil
    V.Plumes, V.SeenPlumes, V.SeenQuakes, V.SeenSurges = {}, {}, {}, {}
    V.QuakePlumeQueue, V.QuakeLog, V.SurgeLog = {}, {}, {}
    V.Quake_, V.QuakeFx, V.Surge_, V.SurgeFx = nil, nil, nil, nil
    V.NativeQuakeOn, V.QuakeMagnitude = false, 0.0
    V.LastPlumeAt, V.LastQuakeEndAt, V.LastSurgeEndAt = -100.0, -1000.0, -1000.0
    V.Stats = {
        plumes = 0, quakes = 0, scriptedQuakes = 0, randomQuakes = 0, mergedQuakes = 0,
        quakePlumes = 0, peakQuake = 0.0,
        surges = 0, scriptedSurges = 0, randomSurges = 0, mergedSurges = 0, peakSurge = 0.0,
    }
    V.FrostLive, V.PlumeLive = {}, {}
    V.PlumeSerial, V.QuakeSerial, V.SurgeSerial = 0, 0, 0
    V.LastStateKey = nil
    V.NextStreamAt, V.NextFrostAt, V.NextNetStateAt = 0.0, 0.0, 0.0

    -- A guest in a network game has no seed until the host's state arrives; it
    -- shows calm weather until then rather than inventing a timeline that
    -- would diverge. Offline and host always have one.
    local seed = tonumber(options.seed)
    if seed == nil and V.IsAuthority then
        seed = math.random(1, 2000000000)
    end
    if seed ~= nil then
        BuildLadder(seed)
        V.Synced = true
    else
        V.Seed = nil
        V.Ladder = nil
        V.Synced = false
        V.PlumeRng = Map.NewRng(13)
        V.QuakeRng = Map.NewRng(16)
        V.SurgeRng = Map.NewRng(17)
        V.TidalPhaseOffset = 0.0
    end

    V.Level = Clamp(tonumber(options.startLevel) or 1, 1, LEVEL_COUNT)
    V.LevelValue = V.Level

    -- Map data.
    local sites = options.sites
    V.FrostPools, V.VentSites = {}, {}
    if sites ~= nil then
        if sites.frost ~= nil then
            V.FrostPools = sites.frost.pools or {}
        end
        if sites.vents ~= nil then
            V.VentSites = Map.MergeVents(sites.vents, V.PlumeMergeRadius)
        end
    end

    local environment = rawget(_G, "Environment")
    if environment ~= nil and type(environment.RegisterEnvironmentModifier) == "function" then
        environment.RegisterEnvironmentModifier("CREuropaWeather", EnvironmentModifier)
        V.EnvModifierRegistered = true
    end

    InitVentTimers()
    V.QuakePlumeQueue = {}
    ScheduleNextQuake()
    ScheduleNextSurge()

    ApplyRung(V.Level, 0.05)
    PinNoWind()

    V.Initialized = true
    Log("initialised; seed=" .. tostring(V.Seed) .. " authority=" .. tostring(V.IsAuthority))
    BroadcastState(true)
end

-- Same real-clock treatment as the other directors: adapters may pass a fixed
-- 1/TPS dt that is really a frame count, so take elapsed time from GetTime.
local function RealDelta(fallbackDt)
    if type(GetTime) ~= "function" then return fallbackDt end
    local now = GetTime()
    if type(now) ~= "number" then return fallbackDt end
    local last = V.LastRealTime
    V.LastRealTime = now
    if last == nil then return 0.0 end
    local delta = now - last
    if delta <= 0.0 or delta > 1.0 then return 0.0 end
    return delta
end

-- Light snow on the cockpit glass (CRWetGlass: sparse flakes that land and melt, no streaks). A
-- constant light level that follows the activity ladder a little and breathes slowly, eased so the
-- glass never jumps. Off with the director, with CRWeather.Quality 0 or with AllowGlassSnow.
local GlassModule = nil
local function Glass()
    if GlassModule == nil then
        local ok, m = pcall(require, "CRWetGlass")
        GlassModule = (ok and type(m) == "table" and type(m.Weather) == "function") and m or false
    end
    return GlassModule or nil
end

local GLASS_SNOW_BASE, GLASS_SNOW_SPAN = 0.22, 0.38   -- level at quiescent, plus the climb to perijove
local GLASS_SNOW_RATE = 0.04                          -- level per second the glass follows the target at

local function UpdateGlassSnow(dt)
    local glass = Glass()
    if glass == nil then return end
    local target = 0.0
    if V.AllowGlassSnow and (tonumber(CRWeather.Quality) or 1.0) > 0.0 then
        local breathe = 0.85 + 0.15 * math.sin(V.Clock * (2.0 * math.pi / 170.0))
        target = (GLASS_SNOW_BASE + GLASS_SNOW_SPAN * V.GetSeverity()) * breathe
    end
    local step = GLASS_SNOW_RATE * dt
    V.GlassSnow = V.GlassSnow + Clamp(target - V.GlassSnow, -step, step)
    glass.Weather("snow", V.GlassSnow)
    if V.GlassSnow > 0.0 or glass.Busy() then glass.Update(0.0) end
end

function V.GetGlassSnow() return V.GlassSnow or 0.0 end

function V.Update(dt)
    if not V.Initialized then V.Init() end
    if not V.Enabled then return end

    dt = tonumber(dt) or 0.0
    if dt > 0.0 then dt = RealDelta(dt) end
    if dt <= 0.0 then
        CRWeather.Update(0.0)
        return
    end

    V.Clock = V.Clock + dt

    UpdateLadder(dt)
    UpdateRandomQuakes()
    UpdateQuake()
    UpdateRandomSurges()
    UpdateSurge()
    UpdateVents(dt)
    UpdateFrostSystems()
    UpdateGlassSnow(dt)

    if V.Clock >= V.NextStreamAt then
        V.NextStreamAt = V.Clock + V.StreamInterval
        local playerPos = LocalPlayerPosition()
        if V.TemplatesReady then
            if V.AllowFrostHaze and #V.FrostPools > 0 then
                StreamSites(V.FrostPools, V.FrostLive, V.MaxLiveFrost, V.FrostStreamIn, V.FrostStreamOut,
                    FrostCreate, FrostDestroy, playerPos)
            end
            if V.AllowPlumes then
                StreamSites(V.VentSites, V.PlumeLive, V.MaxLivePlumes, V.PlumeStreamIn, V.PlumeStreamOut,
                    PlumeCreate, PlumeDestroy, playerPos)
            end
        end
    end

    BroadcastState(false)
    Wake.Update(dt)
    CRWeather.Update(dt)
end

function V.Shutdown()
    if not V.Initialized then return end

    -- A shake must not outlive the mission.
    NativeStopQuake(false)
    V.Quake_, V.QuakeFx, V.Surge_, V.SurgeFx = nil, nil, nil, nil

    Fx_DestroyAll()
    V.FrostLive, V.PlumeLive = {}, {}

    local glass = Glass()
    if glass ~= nil then
        glass.Weather("snow", 0.0)
        pcall(glass.Stop)
    end
    V.GlassSnow = 0.0

    local environment = rawget(_G, "Environment")
    if V.EnvModifierRegistered and environment ~= nil
        and type(environment.UnregisterEnvironmentModifier) == "function"
    then
        environment.UnregisterEnvironmentModifier("CREuropaWeather")
    end
    V.EnvModifierRegistered = false

    CRWeather.ClearWindOverride()
    Wake.Stop()
    CRWeather.Shutdown()
    V.Initialized = false
end


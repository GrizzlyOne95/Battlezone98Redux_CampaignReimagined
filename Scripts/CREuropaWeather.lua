-- Pins the ladder to a rung for a fixed time -- for a set piece on cue.
function V.ForceLevel(index, seconds, transitionSeconds)
    if not V.Initialized then V.Init() end
    if not V.IsAuthority then return false end
    index = Clamp(tonumber(index) or 1, 1, LEVEL_COUNT)
    V.ForcedLevel = index
    V.ForcedUntil = V.Clock + math.max(1.0, tonumber(seconds) or 60.0)
    ApplyRung(index, transitionSeconds)
    BroadcastState(true)
    return true
end

function V.ReleaseForcedLevel()
    V.ForcedLevel = nil
    V.ForcedUntil = nil
    BroadcastState(true)
end

-- Forces one plume now, from the host. siteIndex indexes GetVentSites(); nil
-- picks a vent from the seeded stream (weighted toward the named landmark
-- geysers). power: optional multiplier on the seeded power.
function V.TriggerPlume(siteIndex, power)
    if not V.IsAuthority or not V.Initialized then return false end
    if siteIndex == nil then
        local items = {}
        for i = 1, #V.VentSites do
            items[i] = { weight = V.VentSites[i].major and 2.0 or 1.0, index = i }
        end
        local pick = Map.PickWeighted(V.PlumeRng, items)
        if pick == nil then return false end
        siteIndex = pick.index
    end
    return EruptVent(floor(tonumber(siteIndex) or 0), tonumber(power))
end

-- 0..1: how thick the vent haze is where the local player stands.
function V.GetVentHaze()
    if not V.AllowVentHaze or #V.Plumes == 0 then return 0.0 end
    local p = LocalPlayerPosition()
    if p == nil then return 0.0 end
    local total = 0.0
    for i = 1, #V.Plumes do
        local e = V.Plumes[i]
        local site = V.VentSites[e.site]
        if site ~= nil then
            local d = Distance2D(site.x, site.z, p.x, p.z)
            local near = 1.0 - Clamp(d / V.VentHazeRange, 0.0, 1.0)
            total = total + (V.FallEnvelope(e) * e.power * near * near)
        end
    end
    return Clamp(total, 0.0, 1.0)
end

local function EnvironmentModifier(frame)
    if not V.Enabled then return end
    local fog = frame.fog

    -- Frost haze beside a vent: the view thins, the fog goes white, the ice
    -- scatters a little light. Render fog only -- nothing reads it as sight.
    local haze = V.GetVentHaze()
    if haze > 0.001 then
        if fog ~= nil then
            fog.fogEnd = fog.fogEnd * Lerp(1.0, V.VentHazeFogEnd, haze)
            fog.fogStart = math.min(fog.fogEnd - 1.0, fog.fogStart * Lerp(1.0, V.VentHazeFogStart, haze))
            local tint = V.VentHazeTint * haze
            fog.r = Lerp(fog.r, V.VentHazeColor.r, tint)
            fog.g = Lerp(fog.g, V.VentHazeColor.g, tint)
            fog.b = Lerp(fog.b, V.VentHazeColor.b, tint)
        end
        local c = V.VentHazeLift
        if frame.ambient then
            frame.ambient.r = frame.ambient.r + (c.r * haze)
            frame.ambient.g = frame.ambient.g + (c.g * haze)
            frame.ambient.b = frame.ambient.b + (c.b * haze)
        end
    end

    -- A radiation surge: a violet-green auroral lift and a flicker in the light.
    local surge = V.GetSurgeIntensity()
    if surge > 0.001 then
        local a = V.SurgeAmbient
        local shimmer = Flicker(V.Clock)
        if frame.ambient then
            local k = surge * (0.55 + (0.45 * shimmer))
            frame.ambient.r = frame.ambient.r + (a.r * k)
            frame.ambient.g = frame.ambient.g + (a.g * k)
            frame.ambient.b = frame.ambient.b + (a.b * k)
        end
        local swing = 1.0 + (V.SurgeFlicker * surge * ((2.0 * shimmer) - 1.0))
        if frame.diffuse then
            frame.diffuse.r = frame.diffuse.r * swing
            frame.diffuse.g = frame.diffuse.g * swing
            frame.diffuse.b = frame.diffuse.b * swing
        end
        if fog ~= nil then
            local tint = V.SurgeFogTint * surge
            fog.r = Lerp(fog.r, V.SurgeFogColor.r, tint)
            fog.g = Lerp(fog.g, V.SurgeFogColor.g, tint)
            fog.b = Lerp(fog.b, V.SurgeFogColor.b, tint)
        end
    end
end

V.EnvironmentModifier = EnvironmentModifier


local function DestroyFall(record)
    if record.fall ~= nil then Fx_Destroy(record.fall); record.fall = nil end
end

local function PlumeDestroy(_, record)
    DestroyFall(record)
    Fx_Destroy(record.name)
end

local function FallCount()
    local n = 0
    for _, record in pairs(V.PlumeLive) do
        if record.fall ~= nil then n = n + 1 end
    end
    return n
end

-- The vapour column: rises, holds, dies away over the end of the plume.
local function ColumnEnvelope(e)
    local age = V.Clock - e.start
    local rise = V.PlumeRise
    local fall = math.min(V.PlumeFallMax, e.duration * 0.4)
    if age < 0.0 then return 0.0 end
    if age < rise then return SmoothStep(age / rise) end
    if age < (e.duration - fall) then return 1.0 end
    if age < e.duration then return 1.0 - SmoothStep((age - (e.duration - fall)) / fall) end
    return 0.0
end

-- The crystals: they reach the ground a few seconds after the column starts and
-- keep falling well after it ends, then thin out over the linger.
function V.FallEnvelope(e)
    local age = V.Clock - e.start - V.FallDelay
    if age < 0.0 then return 0.0 end
    local stop = e.duration + V.FallLinger
    if age < V.FallRise then return SmoothStep(age / V.FallRise) end
    if age < e.duration then return 1.0 end
    if age < stop then return 1.0 - SmoothStep((age - e.duration) / V.FallLinger) end
    return 0.0
end

local function ActivePlumeCount()
    local n = 0
    for i = 1, #V.Plumes do
        if (V.Clock - V.Plumes[i].start) < V.Plumes[i].duration then n = n + 1 end
    end
    return n
end

-- A plume begins (host, and by event guests). Purely visual and audible.
function V.BeginPlume(id, siteIndex, duration, power)
    if not V.AllowPlumes then return false end
    siteIndex = floor(tonumber(siteIndex) or 0)
    local site = V.VentSites[siteIndex]
    if site == nil then return false end
    id = tonumber(id)
    if id ~= nil then
        if V.SeenPlumes[id] then return false end
        V.SeenPlumes[id] = true
        V.SeenPlumes[id - 200] = nil
    end

    duration = Clamp(tonumber(duration) or 24.0, 4.0, 90.0)
    power = Clamp(tonumber(power) or 1.0, 0.2, 2.0)
    V.Plumes[#V.Plumes + 1] = {
        id = id, site = siteIndex, start = V.Clock, duration = duration, power = power,
    }
    V.Stats.plumes = V.Stats.plumes + 1
    V.LastPlumeAt = V.Clock

    local p = LocalPlayerPosition()
    if p ~= nil then
        local d = Distance2D(site.x, site.z, p.x, p.z)
        if d < V.PlumeSoundRange then
            PlayLocalSound(V.PlumeSound,
                Clamp(V.PlumeSoundVolume * (1.0 - (d / V.PlumeSoundRange)) + 10, 10, V.PlumeSoundVolume), 90)
        end
    end
    return true
end

local function UpdatePlumes()
    if #V.Plumes == 0 then return end

    local keep = {}
    for i = 1, #V.Plumes do
        local e = V.Plumes[i]
        local column = ColumnEnvelope(e)
        local fall = V.FallEnvelope(e)
        local record = V.PlumeLive[e.site]
        local site = V.VentSites[e.site]
        local age = V.Clock - e.start
        local over = age >= (e.duration + V.FallDelay + V.FallLinger)

        if record ~= nil and site ~= nil then
            Call("SetParticleEmitterEmissionRate", record.name, 1, V.PlumeBurstRate * e.power * column)
            Call("SetParticleEmitterEmissionRate", record.name, 0, PlumeWisp(site) * (1.0 + (2.0 * column)))

            if V.AllowIceFall and fall > 0.02 and record.fall == nil and FallCount() < V.MaxLiveFall then
                record.fall = Fx_Create("fall", "CR/Europa/IceFall", site.x, record.y + V.FallHeight, site.z)
            end
            if record.fall ~= nil then
                Call("SetParticleEmitterEmissionRate", record.fall, 0, V.FallRate * e.power * fall)
            end
            if over then
                Call("SetParticleEmitterEmissionRate", record.name, 1, 0.0)
                Call("SetParticleEmitterEmissionRate", record.name, 0, PlumeWisp(site))
                DestroyFall(record)
            end
        end

        if not over then keep[#keep + 1] = e end
    end
    V.Plumes = keep
end

-- Host: one plume now, from a vent's timer, a quake, or a mission call.
local function EruptVent(siteIndex, powerScale)
    local site = V.VentSites[siteIndex]
    if site == nil then return false end
    local rng = V.PlumeRng
    local range = site.major and V.PlumeMajorPower or V.PlumePower
    local duration = rng.Range(V.PlumeSeconds[1], V.PlumeSeconds[2])
    local power = rng.Range(range[1], range[2]) * (powerScale or 1.0)
    V.PlumeSerial = V.PlumeSerial + 1
    local id = V.PlumeSerial
    if V.BeginPlume(id, siteIndex, duration, power) then
        Send("EuropaPlume", id, siteIndex, duration, power)
        return true
    end
    return false
end

local function VentPeriod(site)
    local period = V.PlumeRng.Range(V.PlumePeriod[1], V.PlumePeriod[2])
    if site.major then period = period * V.PlumeMajorPeriodScale end
    return period
end

-- The host spreads each vent's first plume evenly across one period, in a seeded
-- random order, so the vents are staggered from the first minute.
local function InitVentTimers()
    V.VentTimers = {}
    local n = #V.VentSites
    if n == 0 then return end
    local rng = V.PlumeRng
    local order = {}
    for i = 1, n do order[i] = i end
    for i = n, 2, -1 do
        local j = rng.Int(1, i)
        order[i], order[j] = order[j], order[i]
    end
    local span = (V.PlumePeriod[1] + V.PlumePeriod[2]) * 0.5
    for rank = 1, n do
        local site = order[rank]
        V.VentTimers[site] = V.PlumeFirstDelay + (((rank - 1) + rng.Range(0.1, 0.9)) / n) * span
    end
end

local function UpdateVentSchedule(dt)
    if not (V.IsAuthority and V.Synced and V.AllowPlumes) then return end
    local n = #V.VentSites
    if n == 0 then return end

    local rate = LadderValue("plumeScale") * TidalFactor()
    if V.Episode then rate = rate * V.EpisodeRateBoost end
    local cap = floor(LadderValue("maxPlumes") + 0.5)

    for i = 1, n do
        local t = V.VentTimers[i]
        if t == nil then
            t = VentPeriod(V.VentSites[i])
        end
        t = t - (dt * rate)
        if t <= 0.0 then
            local blocked = ActivePlumeCount() >= cap or (V.Clock - V.LastPlumeAt) < V.PlumeMinSpacing
            if blocked then
                t = V.PlumeRng.Range(V.PlumeRetry[1], V.PlumeRetry[2])
            else
                EruptVent(i, 1.0)
                t = VentPeriod(V.VentSites[i])
            end
        end
        V.VentTimers[i] = t
    end

    -- A vent a strong quake opened.
    if #V.QuakePlumeQueue > 0 then
        local keep = {}
        for i = 1, #V.QuakePlumeQueue do
            local item = V.QuakePlumeQueue[i]
            if V.Clock >= item.at then
                if EruptVent(item.site, 1.1) then V.Stats.quakePlumes = V.Stats.quakePlumes + 1 end
            else
                keep[#keep + 1] = item
            end
        end
        V.QuakePlumeQueue = keep
    end
end

local function UpdateVents(dt)
    if not V.AllowPlumes or not V.TemplatesReady then
        for index, record in pairs(V.PlumeLive) do
            PlumeDestroy(index, record)
            V.PlumeLive[index] = nil
        end
    end
    UpdateVentSchedule(dt)
    UpdatePlumes()
end

-- =============================================================================
-- Quakes (tidal ice quakes)
-- =============================================================================

local function EnvelopeAt(d, riseFrac, fallFrac, age, minRise, minFall)
    local rise = math.max(minRise, d * riseFrac)
    local fall = math.max(minFall, d * fallFrac)
    if rise + fall > d then
        local k = d / (rise + fall)
        rise, fall = rise * k, fall * k
    end
    if age <= 0.0 then return 0.0 end
    if age < rise then return SmoothStep(age / rise) end
    if age < (d - fall) then return 1.0 end
    if age < d then return 1.0 - SmoothStep((age - (d - fall)) / fall) end
    return 0.0
end

local function QuakeEnvelopeAt(q, age)
    return EnvelopeAt(q.duration, V.QuakeRise, V.QuakeFall, age, 0.15, 0.4)
end

-- 0 with no quake; otherwise strength x envelope (0..1).
function V.GetQuakeIntensity()
    local q = V.Quake_
    if q == nil then return 0.0 end
    return q.strength * QuakeEnvelopeAt(q, V.Clock - q.start)
end


        name          = row.name,
        precipitation = {
            {
                system   = "cr_wx_europa_ice",
                template = "CR/Weather/SnowLight",
                offset   = { x = 0.0, y = 28.0, z = 0.0 },
                quota    = row.quota,
                emitters = {
                    [0] = {
                        rate     = row.rate,
                        velocity = { 1.0, 2.2 },   -- low gravity: a slow fall
                        ttl      = { 9.0, 13.0 },
                        angle    = 5.0,            -- near-vertical: no wind to scatter it
                        color    = {
                            start  = { r = 0.90, g = 0.95, b = 1.00, a = row.a },
                            finish = { r = 0.80, g = 0.88, b = 1.00, a = row.a * 0.6 },
                        },
                    },
                },
            },
        },
        sky           = nil,
        fog           = { r = row.fog[1], g = row.fog[2], b = row.fog[3], fogStart = row.fog[4], fogEnd = row.fog[5] },
        ambient       = { r = row.ambient[1], g = row.ambient[2], b = row.ambient[3] },
        diffuse       = { r = row.diffuse[1], g = row.diffuse[2], b = row.diffuse[3] },
        sunPowerScale = row.sun,
        wind          = { x = 0.0, y = -1.0, z = 0.0 },
        windSpeed     = 1.0,
        lightning     = nil,
        transitionIn  = row.tin,
        transitionOut = row.tout,
    }
end

-- Exposed so a test (or a settings page) can inspect what was registered.
function V.RegisterPresets()
    local presets = CRWeatherPresets.Presets
    if type(presets) ~= "table" then return 0 end
    local added = 0
    for i = 1, #PRESET_ROWS do
        local row = PRESET_ROWS[i]
        if presets[row.name] == nil then
            presets[row.name] = BuildPreset(row)
            added = added + 1
        end
    end
    return added
end

function V.GetPresetNames()
    local names = {}
    for i = 1, #PRESET_ROWS do names[i] = PRESET_ROWS[i].name end
    return names
end


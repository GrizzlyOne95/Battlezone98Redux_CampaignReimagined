    Fx_Destroy(record.name)
end

-- Fallout beside a sheet thickens it: how much ice is falling within range.
local function FalloutNear(x, z)
    local total = 0.0
    for i = 1, #V.Plumes do
        local e = V.Plumes[i]
        local site = V.VentSites[e.site]
        if site ~= nil then
            local near = 1.0 - Clamp(Distance2D(site.x, site.z, x, z) / V.FrostFallRange, 0.0, 1.0)
            if near > 0.0 then
                total = total + (V.FallEnvelope(e) * e.power * near)
            end
        end
    end
    return Clamp(total, 0.0, 1.0)
end

local function UpdateFrostSystems()
    if V.Clock < V.NextFrostAt then return end
    V.NextFrostAt = V.Clock + 1.0
    for _, record in pairs(V.FrostLive) do
        local boost = 1.0 + (V.FrostFallBoost * FalloutNear(record.pool.x, record.pool.z))
        local rate = FrostBaseRate(record.pool, boost)
        if math.abs(rate - record.rate) > 0.15 then
            record.rate = rate
            Call("SetParticleEmitterEmissionRate", record.name, 0, rate)
        end
    end
end


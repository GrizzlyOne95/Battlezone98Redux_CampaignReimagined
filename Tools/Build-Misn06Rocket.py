"""Build the CR-authored CCA rocket and its RGBA8 game textures.

python Tools/Build-Misn06Rocket.py --blender <blender.exe> --render
Requires Blender 4.5+ and Pillow. --textures-only converts already baked sources.
The previous Resurgence extraction is retained in Extract-Misn06RocketLegacy.py.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def build_fx_layout(geometry):
    jets=geometry['nozzles']
    assert len(jets)==8
    layout='-- Generated by Build-Misn06Rocket.py from the authored bell exits.\nreturn { nozzleY = %.9f, nozzles = {\n' % geometry['nozzle_plane']
    layout+=''.join('    {%.9f, %.9f},\n' % (p[0],p[2]) for p in jets)
    layout+='} }\n'
    (ROOT/'Scripts/CR06RocketLayout.lua').write_text(layout,encoding='utf-8',newline='\n')
    target=ROOT/'Materials/cr06_launch.particle.payload'
    tail='particle_system CR/M06/Smoke'+target.read_text().split('particle_system CR/M06/Smoke',1)[1]
    blocks=[]
    for kind,mat,width,height,quota,ttl0,ttl1,v0,v1,angle in [
        ('Core','CR06/HotCore',4.8,7,96,.10,.22,12,20,2),
        ('Plume','CR06/Exhaust',4,14,320,.35,.65,100,150,5)]:
        text=('// Generated eight-nozzle engine layer; positions are set from the actor basis.\n'
              'particle_system CR/M06/%s\n{\n    material %s\n    particle_width %g\n'
              '    particle_height %g\n    quota %d\n    cull_each true\n    sorted false\n'
              '    local_space false\n    billboard_type %s\n') % (kind,mat,width,height,quota,'point' if kind=='Core' else 'oriented_self')
        for p in jets:
            text+=('    emitter Point\n    {\n        position %.9f 0 %.9f\n        angle %g\n'
                   '        emission_rate 0\n        time_to_live_min %g\n        time_to_live_max %g\n'
                   '        direction 0 -1 0\n        velocity_min %g\n        velocity_max %g\n'
                   '        colour_range_start 1 1 1 0.95\n        colour_range_end 0.8 0.8 0.8 0.7\n    }\n') % (p[0],p[2],angle,ttl0,ttl1,v0,v1)
        text+='    affector ColourFader\n    {\n        alpha %g\n    }\n' % (-4 if kind=='Core' else -1.2)
        if kind=='Plume':text+='    affector Scaler\n    {\n        rate 8\n    }\n'
        blocks.append(text+'}\n')
    target.write_text('\n'.join(blocks)+'\n'+tail,encoding='utf-8',newline='\n')


def build(blender, render=False, textures_only=False):
    if not textures_only:
        command = [blender, '-b', '--factory-startup', '-t', '4', '--python',
                   str(ROOT/'Tools/Author-Misn06Rocket.py'), '--']
        if render: command.append('--render')
        subprocess.run(command, check=True)
    for suffix in ('d','n','s','e'):
        source=ROOT/'References/Misn06Rocket/Textures'/('cr06rok_'+suffix+'.png')
        image=Image.open(source).convert('RGBA')
        # Uncompressed RGBA8 avoids the native DX11 BC3 colour-path failure.
        image.save(ROOT/'Assets/Textures'/('cr06rok_'+suffix+'.dds'))
    geometry=json.loads((ROOT/'References/Misn06Rocket/geometry.json').read_text())
    build_fx_layout(geometry)
    paths=[ROOT/'Assets/ModelFixes'/('cr06rok.'+s) for s in ('mesh','geo','sdf')]
    paths += [ROOT/'Assets/Textures'/('cr06rok_'+s+'.dds') for s in ('d','n','s','e')]
    geometry['sha256']={str(p.relative_to(ROOT)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
    (ROOT/'References/Misn06Rocket/build.json').write_text(json.dumps(geometry,indent=2)+'\n')
    print('Built CCA Mars rocket:',geometry['triangles'],'triangles; 8 nozzle anchors.')


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--blender',default=shutil.which('blender'))
    ap.add_argument('--render',action='store_true')
    ap.add_argument('--textures-only',action='store_true')
    args=ap.parse_args()
    if not args.blender and not args.textures_only:ap.error('--blender is required when Blender is not on PATH')
    build(args.blender,args.render,args.textures_only)

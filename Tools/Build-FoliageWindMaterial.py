"""Write Materials/cr17_wind.material from Materials/cr17_surface.material.

CR17/CutoutWind is CR17/Cutout with every vertex program swapped for its
cr17_wind.program twin and windShape passed through, so the two stay in step
across all of Cutout's quality schemes, LODs and the glow pass. Rerun this
after changing CR17/Cutout or CR17/CutoutCaster/Foliage.

The leaf materials are declared here as well, not in cr17_jungle.material,
because a material can only inherit from one parsed earlier in the same file
or brought in with `import`. These are the only names the baked meshes use.

Usage: python -I Tools/Build-FoliageWindMaterial.py [--check]
  --check  fail if Materials/cr17_wind.material is not what this would write
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Materials" / "cr17_surface.material"
TARGET = ROOT / "Materials" / "cr17_wind.material"

PROGRAMS = {
    "CR17_Surface_PSSM_vertex": "CR17_Wind_PSSM_vertex",
    "CR17_Surface_Shadow_vertex": "CR17_Wind_Shadow_vertex",
    "CR17_Surface_vertex": "CR17_Wind_Plain_vertex",
    "CR17_Surface_Caster_vertex": "CR17_Wind_Caster_vertex",
}

# windShape: bend (m), sway rate (rad/s), flutter (m), flutter rate (rad/s).
# Bend is reached at 20 m/s of wind; CRFoliageWind scales below that.
TREE_SHAPE = "0.6 0.7 0.18 5.5"     # the trunk is bark and stays put
GROUND_SHAPE = "0.45 1.6 0.07 8.0"  # ferns, fronds and reeds, 1-3 m tall

HEADER = """// Generated by Tools/Build-FoliageWindMaterial.py from cr17_surface.material.
// Edit that tool, not this file.
//
// Wind-swayed foliage. CR17/CutoutWind is CR17/Cutout on the cr17_wind.program
// vertex programs; meshes reference it through CR17/LeavesWind (tree canopies)
// and CR17/GroundWind (StaticGeometry ground cover), both baked by
// Tools/Bake-FoliageSway.py. CRFoliageWind writes the live wind into the pass
// emissive colour, so the material is still until it runs.
"""


def block(text, name):
    match = re.search(r"^material " + re.escape(name) + r"\s*$", text, re.M)
    if not match:
        raise SystemExit(f"{SOURCE.name}: no material {name}")
    depth, i = 0, text.index("{", match.end())
    while True:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[match.start():i + 1]
        i += 1


def windify(text, rename, shape):
    text = text.replace(text.split("\n", 1)[0], "material " + rename, 1)
    for old, new in PROGRAMS.items():
        text, count = re.subn(
            r"(\t+)vertex_program_ref " + old + r"\n(\t+)\{\n\t+\}",
            lambda m: (f"{m.group(1)}vertex_program_ref {new}\n{m.group(2)}{{\n"
                       f"{m.group(2)}\tparam_named windShape float4 {shape}\n{m.group(2)}}}"),
            text)
    if re.search(r"vertex_program_ref CR17_Surface_", text):
        raise SystemExit(f"{rename}: a CR17_Surface vertex program was not swapped")
    return text


def main():
    source = SOURCE.read_bytes().decode("utf-8").replace("\r\n", "\n")
    cutout = windify(block(source, "CR17/Cutout"), "CR17/CutoutWind", "$windShape")
    cutout = cutout.replace('\tset $caster "CR17/CutoutCaster/white"',
                            '\tset $caster "CR17/CutoutCaster/FoliageWind"\n'
                            f'\tset $windShape "{GROUND_SHAPE}"', 1)
    if "set $windShape" not in cutout:
        raise SystemExit("CR17/Cutout no longer sets $caster to CR17/CutoutCaster/white")
    caster = windify(block(source, "CR17/CutoutCaster/Foliage"), "CR17/CutoutCaster/FoliageWind", TREE_SHAPE)

    leaves = """material CR17/LeavesWind : CR17/CutoutWind
{
\tset_texture_alias DiffuseMap cr17_foliage.dds
\tset_texture_alias NormalMap cr17_flat.dds
\tset_texture_alias SpecularMap cr17_black.dds
\tset_texture_alias EmissiveMap cr17_black.dds
\tset $cutoutParams "0.45 0.5 0.6 2048"
\tset $specular "0.1 0.1 0.1"
\tset $shininess "16"
\tset $windShape "%s"
}""" % TREE_SHAPE
    ground = leaves.replace("CR17/LeavesWind", "CR17/GroundWind").replace(TREE_SHAPE, GROUND_SHAPE)
    ground = ground.replace("\tset $windShape", '\tset $caster "CR17/NoShadowCaster"\n\tset $windShape')

    text = "\n\n".join([HEADER.rstrip("\n"), caster, cutout, leaves, ground]) + "\n"
    data = text.replace("\n", "\r\n").encode("utf-8")
    if "--check" in sys.argv[1:]:
        # Git stores the file LF; a Linux checkout has no CRs. Compare the text.
        if not TARGET.exists() or TARGET.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8"):
            raise SystemExit(f"{TARGET.relative_to(ROOT)} is stale; rerun Tools/Build-FoliageWindMaterial.py")
        print(f"{TARGET.relative_to(ROOT)} is current")
        return
    TARGET.write_bytes(data)
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

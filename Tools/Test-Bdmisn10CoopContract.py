#!/usr/bin/env python3
"""bdmisn10 co-op map contract: the labels, paths and teams Scripts/bd10cr.lua names exist in Missions/bd10cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/Build-CoopMap.py); the script, the sites and the doc are always checked.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
lua_full = (ROOT / "Scripts/bd10cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local NativeGetNearestUnitOnTeam", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = 5" in config and "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRElysiumSitesBD10"' in config and 'module = "CRElysiumWeather"' in config
assert "failDes" not in config.replace("-- No failDes", ""), "the game ships no bd10 loss debrief"
assert "safeRadius = 350" in config, "the concealment ring is inside the 400 m ambush trigger"
assert 'orders = { "Hunt" }' in config
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
spawned = set(re.findall(r"\"(c\w+)\"", re.search(r"local defenceUnits = (.*?)\nlocal patrols", live, re.S)[1])) | \
    set(re.findall(r"\"(c\w+)\"", re.search(r"local patrolUnits = (.*?)\n\}\n", live, re.S)[1]))
assert scaled == spawned == {"cvfigh", "cvltnk", "cvtnk", "cvwalk", "cvhtnk"}, (scaled, spawned)
sites = ROOT / "Scripts/CRElysiumSitesBD10.lua"
assert sites.is_file() and 'mission = "bdmisn10"' in sites.read_text(encoding="utf-8"), "generated Elysium sites belong to bdmisn10"
for module in ("CRElysiumWeather", "CRCCARuntime"):
    assert (ROOT / ("Scripts/%s.lua" % module)).is_file(), module
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio and objectives: none is invented
wavs = sorted(set(re.findall(r'"(bd10\d+\.wav)"', lua_full)))
assert wavs == ["bd10001.wav", "bd10002.wav", "bd10003.wav"], wavs
for wav in wavs:
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
assert not re.search(r'"bd10\d+\.wav"', cr_text), "the game ships no unused bd10 voice line; the CR layer plays none"
otfs = sorted(set(re.findall(r'"(bd10\d+\.otf)"', lua_full)))
assert otfs == ["bd10001.otf"] + ["bd1000%d.otf" % n for n in range(2, 8)], otfs
assert set(re.findall(r'"(bd10\d+\.otf)"', live)) == {"bd10001.otf"}, "the body uses only the briefing objective"
assert "bd10win.des" in live  # the debrief ships with the game, not in this tree

# ---------------------------------------------------------------- the doc
doc = (ROOT / "Docs/BDMISN10_COOP.md").read_text(encoding="utf-8")
for heading in ("## Stock bugs and co-op fixes in the CR layer", "## Restored content", "## Live checklist"):
    assert heading in doc, heading
assert "`bd10002.otf`..`bd10007.otf`" in doc, "the restored objective range is documented"

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd10cr.bzn"
if not bzn_path.is_file():
    print("bdmisn10 co-op contract: map checks SKIPPED, Missions/bd10cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn10\n" in text and "msn_filename = bd10cr.bzn" in text

objects, starts = {}, []
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    assert perceived == team, "perceived team follows the move: " + str(label and label[1])
    if label:
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# Every handle the body asks for is a map object, on the enemy side.
assert re.search(r'GetHandle\("destroy_" \.\. i\)', live), "the body reads destroy_1..6 in a loop"
for n in range(1, 7):
    assert objects["destroy_%d" % n][1] == 5, "the six key buildings are the co-op enemy's"
assert objects["player"][1] == 1
# Every path the body or the CR layer names exists.
used = {lit for lit in re.findall(r'"(\w+)"', live + cr_text) if lit in set(paths)}
rally = re.search(r'rallyPoints = \{ \[0\] = "(\w+)" \}', config)[1]
used.add(rally)
expected = {"defend_a", "defend_b", "defend_c", "defend_d", "patrol_a", "patrol_b", "patrol_c", "patrol_d",
            "camera_start", "camera_apc", "camera_end", "navcam_end", "apc", "apc_path", "portal", "recycler",
            "recycler_path", "capture", "backup"}
assert used == expected, (sorted(used ^ expected))
assert used <= set(paths), "every path the body names exists: " + str(used - set(paths))
# The weather strikes the drop zone path and the ambush spots.
assert 'strikePath("recycler")' in cr_text
# The seven vents the weather uses are geysers the map carries (the sites file is generated from them).
vents = re.findall(r'label = "(\w+)"', sites.read_text(encoding="utf-8").split("vents = {", 1)[1])
assert len(vents) == 7
for label in vents:
    base = label[:-len("_geyser")]
    assert any(k.startswith(base) for k in objects) or label in objects, "vent is a map geyser: " + label

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd10cr.vxt"
ini = ROOT / "Config/bd10cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every named map path
unused = sorted(set(paths) - used)
for name in unused:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
print("bdmisn10 co-op contract passed: %d objects, %d paths, %d scripted path names, Elysium sites present; %d paths unused (documented)"
      % (len(objects), len(paths), len(used), len(unused)))

"""Point CR's base materials at programs that work with or without OpenShim.

CR_BZBase and CR_BZTerrainBase run OpenShim's OSE_* programs, which exist
only after Setup has installed OpenShim. Before that (a player who has just
subscribed and is launching Setup), a pass that names a missing program has
no shaders, and DX11 closes the game with "complete render failure".

For every program the materials use, this writes a unified CR_ShimOrStock_*
program whose delegates list OpenShim's leaves first and, where the stock game
has a same-named program, its leaves after them. Ogre takes the first delegate
that exists, so OpenShim installs keep the OSE_ shaders and fresh installs fall
back to stock. The en-*/og-* programs have no stock twin, so their wrappers list
only OpenShim's leaves: without OpenShim those techniques are unsupported
instead of a compile error per material, and only OpenShim selects those
schemes anyway. Rerun after adding a program ref; it reads OpenShim's leaf
names from --openshim (default: $BZR_OPENSHIM_REPO).
"""
import argparse
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATERIALS = [ROOT / "Materials/CR_BZBase.material", ROOT / "Materials/CR_BZTerrainBase.material"]
PROGRAMS = ROOT / "Shaders/CR_ShimOrStock.program"
PREFIX = "CR_ShimOrStock_"
REF = re.compile(r"\b(vertex|fragment)_program_ref\s+(?:OSE_|" + PREFIX + r")((?:Base|Terrain)\w+_(?:vertex|fragment))\b")
# Every stock Base*/Terrain* program delegates to these leaves; EN/OG are OpenShim-only.
STOCK_LEAVES = ("GLSLES", "GLSL", "HLSL4", "HLSL")
UNIFIED = re.compile(r"^\w+_program\s+(OSE_\S+)\s+unified\s*\{(.*?)^\}", re.M | re.S)


def stock_twin(name):
    return not re.match(r"(Base|Terrain)(EN|OG)", name)


def openshim_leaves(repo):
    leaves = {}
    for path in (repo / "resources/renderer/enhanced").glob("*.program"):
        for name, body in UNIFIED.findall(path.read_text(encoding="latin-1")):
            leaves[name] = re.findall(r"^\s*delegate\s+(\S+)", body, re.M)
    return leaves


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--openshim", type=Path, default=os.environ.get("BZR_OPENSHIM_REPO"), help="OpenShim repo checkout")
    args = parser.parse_args()
    if not args.openshim:
        parser.error("--openshim or BZR_OPENSHIM_REPO is required")
    ose = openshim_leaves(args.openshim)

    used = {}
    for path in MATERIALS:
        text = path.read_bytes().decode("latin-1")
        for kind, name in REF.findall(text):
            used[name] = kind
        new = REF.sub(lambda m: f"{m.group(1)}_program_ref {PREFIX}{m.group(2)}", text)
        if new != text:
            path.write_bytes(new.encode("latin-1"))

    blocks = ["// GENERATED by Tools/Generate-ShimOrStockPrograms.py -- do not edit.\n"
              "// OpenShim's OSE_ leaves first, then any stock leaves as the fresh-install fallback.\n"]
    for name, kind in sorted(used.items()):
        delegates = list(ose[f"OSE_{name}"])
        if stock_twin(name):
            delegates += [f"{name}{leaf}" for leaf in STOCK_LEAVES]
        body = "".join(f"\tdelegate {d}\n" for d in delegates)
        blocks.append(f"{kind}_program {PREFIX}{name} unified\n{{\n{body}}}\n")
    PROGRAMS.write_text("\n".join(blocks), newline="\r\n")
    print(f"{len(used)} programs -> {PROGRAMS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""bdmisn15 co-op map contract: the labels, paths and teams Scripts/bd15cr.lua names exist in Missions/bd15cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/Build-CoopMap.py); the script, the sites, the texts and the doc are always checked.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
lua_full = (ROOT / "Scripts/bd15cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local PLAYERS =", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = 5" in config and "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRGanymedeSitesBD15"' in config and 'module = "CREuropaWeather"' in config
assert 'failDes = "bd15lose.des"' in config
assert 'wonFlags = { "doingExplosion" }' in config
rally = re.search(r'rallyPoints = \{ \[0\] = "(\w+)" \}', config)[1]
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
spawned = set(re.findall(r"\"(cv\w+)\"", live))
assert scaled == spawned == {"cvfigh", "cvltnk", "cvtnk", "cvapc", "cvhtnk", "cvhraz", "cvhaul"}, (scaled, spawned)
sites = ROOT / "Scripts/CRGanymedeSitesBD15.lua"
assert sites.is_file() and 'mission = "bdmisn15"' in sites.read_text(encoding="utf-8"), "generated Ganymede sites belong to bdmisn15"
for module in ("CREuropaWeather", "CRCCARuntime"):
    assert (ROOT / ("Scripts/%s.lua" % module)).is_file(), module
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio and objectives
body_wavs = sorted(set(re.findall(r'"(bd15\d+\.wav)"', live)))
assert body_wavs == ["bd150%02d.wav" % n for n in (1, 2, 3, 4, 5, 6, 7, 10, 11, 12)], body_wavs
restored_wavs = sorted(set(re.findall(r'"(bd15\d+\.wav)"', cr_text)))
# the three the DLL never plays are restored; bd15011 is replayed for a mirror that breaches the site
assert restored_wavs == ["bd15008.wav", "bd15009.wav", "bd15011.wav", "bd15013.wav"], restored_wavs
durations = (ROOT / "Config/durations.csv").read_text(encoding="utf-8")
for wav in sorted(set(body_wavs) | set(restored_wavs)):
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
    assert wav + "," in durations, "no duration for " + wav
unused = {"bd15008.wav", "bd15009.wav", "bd15013.wav"}
assert unused.isdisjoint(body_wavs) and unused <= set(restored_wavs), "the restored lines are the ones the body never plays"
assert sorted(set(re.findall(r'"(bd15\d+\.otf)"', live + cr_text))) == ["bd15001.otf", "bd15002.otf"]
assert "bd15win.des" in live and "bd15lose.des" in live  # the debriefs ship with the game, not in this tree
assert "RESTORED_COUNTDOWN_LINES" in cr_text and "RESTORED_SAFE_DISTANCE" in cr_text

# ---------------------------------------------------------------- the doc
doc = (ROOT / "Docs/BDMISN15_COOP.md").read_text(encoding="utf-8")
for heading in ("## Stock bugs and co-op fixes in the CR layer", "## Restored content", "## Live checklist",
                "## Weather: Ganymede"):
    assert heading in doc, heading
for wav in sorted(unused):
    assert "`" + wav + "`" in doc, "undocumented restored line: " + wav
assert "RESTORED_COUNTDOWN_LINES" in doc and "RESTORED_SAFE_DISTANCE" in doc

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd15cr.bzn"
if not bzn_path.is_file():
    print("bdmisn15 co-op contract: map checks SKIPPED, Missions/bd15cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn15\n" in text and "msn_filename = bd15cr.bzn" in text

objects, starts = {}, []
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    assert perceived == team, "perceived team follows the move: " + str(label and label[1])
    if label:
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# The enemy launch site and the Black Dog base are authored objects on their sides.
assert objects["launch"] == ("cblpada", 5), "the transport's launch pad is the co-op enemy's"
assert objects[rally][1] == 1, "the respawn base is a Black Dog object"
# Every path the body or the CR layer names exists.
used = {lit for lit in re.findall(r'"(\w+)"', live + cr_text) if lit in set(paths)}
# The wave roads are named by direction in the body ("spawn_" .. direction .. "_wave", "path_" .. direction .. "_wave").
assert 'BuildObject(odf, 2, "spawn_" .. direction .. "_wave")' in live and 'Goto(h, "path_" .. direction .. "_wave")' in live
directions = set(re.findall(r'Wave\("(\w+)"', live)) | set(re.findall(r'Spawn\("\w+", "(\w+)"\)', live))
assert directions == {"east", "west", "north", "south"}, directions
for direction in directions:
    used |= {"spawn_%s_wave" % direction, "path_%s_wave" % direction}
expected = {"spawn_east_wave", "path_east_wave", "spawn_west_wave", "path_west_wave", "spawn_north_wave",
            "path_north_wave", "spawn_south_wave", "path_south_wave", "chin_launch", "spawn_explosion1", "camera_finale"}
assert used == expected, (sorted(used ^ expected))
assert used <= set(paths), "every path the body names exists: " + str(used - set(paths))
# Map note: "chin_launch" is authored twice (a one-point path at the pad, and a nine-point loop west of it); the DLL and
# this port read whichever the engine finds first, which the file orders as the one-point path.
assert paths.count("chin_launch") == 2
first = text.index("label = chin_launch")
assert re.search(r"pointCount \[1\] =\n1\n", text[first:first + 120]), "the first chin_launch is the one-point path"
# The weather strikes vents the map carries (the sites file is generated from them).
vents = re.findall(r'label = "(\w+)"', sites.read_text(encoding="utf-8").split("vents = {", 1)[1])
assert len(vents) == 6, vents
for label in vents:
    assert label in objects and objects[label][0] == "eggeizr1", "vent is a map geyser: " + label
for label in re.findall(r'plume\("(\w+)"\)', cr_text):
    assert label in vents, "the weather names a vent the sites file has: " + label

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd15cr.vxt"
ini = ROOT / "Config/bd15cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every unused map path
unused_paths = sorted(set(paths) - used)
for name in unused_paths:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
print("bdmisn15 co-op contract passed: %d objects, %d paths, %d scripted path names, Ganymede sites present; %d paths unused (documented)"
      % (len(objects), len(paths), len(used), len(unused_paths)))

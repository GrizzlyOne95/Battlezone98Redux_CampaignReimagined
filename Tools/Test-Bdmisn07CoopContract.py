#!/usr/bin/env python3
"""bdmisn07 co-op map contract: the labels, paths and teams Scripts/bd07cr.lua names exist in Missions/bd07cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/Build-CoopMap.py); the script, the sites and the doc are always checked.
"""
from collections import Counter
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
lua_full = (ROOT / "Scripts/bd07cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local NativeGetScrap", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = 5" in config and "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRElysiumSitesBD07"' in config and 'module = "CRElysiumWeather"' in config
assert "ops =" not in config, "Elysium shares the Venus op names (the runtime default)"
assert 'failDes = "bd07lose.des"' in config
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
built_odfs = set(re.findall(r'BuildObject\("(\w+)", 2, ', live))
assert scaled == built_odfs == {"cvfigh", "cvltnk"}, (scaled, built_odfs)
sites = ROOT / "Scripts/CRElysiumSitesBD07.lua"
assert sites.is_file() and 'mission = "bdmisn07"' in sites.read_text(encoding="utf-8"), "generated Elysium sites belong to bdmisn07"
for module in ("CRElysiumWeather", "CRVenusWeather", "CRCCARuntime"):
    assert (ROOT / ("Scripts/%s.lua" % module)).is_file(), module
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua|aip)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio: every line has a subtitle, none is invented
wavs = sorted(set(re.findall(r'"(bd07\d+\.wav)"', lua_full)))
assert wavs == ["bd07001.wav", "bd07002.wav", "bd07003.wav", "bd07004.wav"], wavs
for wav in wavs:
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
assert set(re.findall(r'"(bd07\d+\.wav)"', cr_text)) == set(), "the shipped game carries no unused bd07 voice line"
# The debriefs bd07win.des / bd07lose.des ship with the game, not in this tree.
assert "bd07win.des" in live and "bd07lose.des" in live

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd07cr.bzn"
doc = (ROOT / "Docs/BDMISN07_COOP.md").read_text(encoding="utf-8")
if not bzn_path.is_file():
    print("bdmisn07 co-op contract: map checks SKIPPED, Missions/bd07cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn07\n" in text and "msn_filename = bd07cr.bzn" in text

objects, starts, labels = {}, [], Counter()
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    assert perceived == team, "perceived team follows the move: " + str(label and label[1])
    if label:
        labels[label[1]] += 1
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# Every handle the body asks for is a map object, on the right side.
handles = set(re.findall(r'GetHandle\("(\w+)"\)', live))
assert handles <= set(objects), "every GetHandle label is a map object: " + str(handles - set(objects))
for label in handles:
    odf, team = objects[label]
    if label in ("recycler", "myfactory", "my_hq") or label.startswith("nav_"):
        assert team == 1, "Black Dog side: " + label
    else:
        assert team == 5, "Chinese side (co-op enemy team): " + label
assert objects["recycler"] == ("bvrecyc", 1) and objects["myfactory"] == ("bvmufb", 1) and objects["my_hq"] == ("bbhqcp", 1)
assert len(handles) == 3 + 11 + 3 + 8 + 2, "3 to save, 11 to destroy, 11 wave units, 2 beacons: %d" % len(handles)
for n in range(1, 7):
    assert objects["chin_scout%d" % n][0] == "cvfigh", "wave scouts are Chinese fighters"
rally = re.search(r'rallyPoints = \{ \[0\] = "(\w+)" \}', config)[1]
assert rally in objects, "rally point is a map object"
# The body reads the 11 structures it must destroy by name; a label that is authored twice resolves to one of them.
duplicated = sorted(l for l, n in labels.items() if n > 1 and l in handles)
assert duplicated == ["chin_scout1", "chin_scout2", "chin_scout3"], duplicated
for name in duplicated:
    assert "`" + name + "`" in doc, "undocumented duplicate label: " + name
# Every path the body or the CR layer names exists.
used = set(re.findall(r'"(attack_path\d|annoy_\d)"', live)) | set(re.findall(r'PathExists\("(\w+)"\)', cr_text))
used |= set(re.findall(r'BuildObject\("\w+", 2, "(\w+)"\)', live))
assert used == {"attack_path1", "attack_path2", "annoy_1"}, used
assert used <= set(paths), "every path the body names exists: " + str(used - set(paths))
fallback = re.search(r"fallbackEntries = \{([^}]*)\}", config)[1]
fallback_paths = re.findall(r'"(\w+)"', fallback)
assert fallback_paths and "annoy_1" not in fallback_paths, "there are alternative staging points"
for name in fallback_paths:
    assert name in paths, "fallback spawn entry exists: " + name
assert set(fallback_paths) <= used, "fallbacks are the body's own approaches"

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd07cr.vxt"
ini = ROOT / "Config/bd07cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every named map path
unused = sorted(set(paths) - used)
for name in unused:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
assert unused == ["edge_path"], unused
assert (ROOT / "Docs/CCA_COOP_RUNTIME.md").is_file()
print("bdmisn07 co-op contract passed: %d labels, %d paths, %d scripted path/label names, Elysium sites present; %d path unused (documented)"
      % (len(objects), len(paths), len(used) + len(handles), len(unused)))

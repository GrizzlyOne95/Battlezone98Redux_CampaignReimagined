#!/usr/bin/env python3
"""bdmisn05 co-op map contract: the labels, paths and teams Scripts/bd05cr.lua names exist in Missions/bd05cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/Build-CoopMap.py); the script, the sites and the doc are always checked.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
lua_full = (ROOT / "Scripts/bd05cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--\[==\[.*?\]==\]", "", live, flags=re.S)  # the DLL's disabled code stays disabled
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local NativeBuildObject", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = 5" in config and "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRGanymedeSitesBD05"' in config and 'module = "CREuropaWeather"' in config
assert 'ops = { "EuropaState", "EuropaPlume", "EuropaQuake", "EuropaSurge" }' in config
assert "failDes" not in config.replace("-- No failDes", ""), "the game ships no bd05 loss debrief"
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
spawn_odfs = set(re.findall(r'SpawnUnit\(\d+, "(\w+)"', live))
assert scaled == spawn_odfs == {"cvfigh", "cvltnk", "cvtnk", "cvhraz", "cvwalk", "cvartl"}, (scaled, spawn_odfs)
sites = ROOT / "Scripts/CRGanymedeSitesBD05.lua"
assert sites.is_file() and 'mission = "bdmisn05"' in sites.read_text(encoding="utf-8"), "generated Ganymede sites belong to bdmisn05"
sites_text = sites.read_text(encoding="utf-8")
vents = re.findall(r'label = "(\w+)"', sites_text.split("vents = {", 1)[1])
for label in set(re.findall(r'plume\("(\w+)"\)', cr_text)):
    assert label in vents, "weather beat names a vent the sites carry: " + label
for module in ("CREuropaWeather", "CRCCARuntime"):
    assert (ROOT / ("Scripts/%s.lua" % module)).is_file(), module
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio: every line has a subtitle, none is invented
wavs = sorted(set(re.findall(r'"(bd05\d+\.wav)"', lua_full)))
assert wavs == ["bd05001.wav", "bd05002.wav", "bd05003.wav", "bd05004.wav", "bd05005.wav", "bd05006.wav", "bd05007.wav"], wavs
for wav in wavs:
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
body_wavs = set(re.findall(r'"(bd05\d+\.wav)"', live))
assert body_wavs == {"bd05001.wav", "bd05002.wav", "bd05004.wav", "bd05005.wav", "bd05006.wav"}, body_wavs
assert set(re.findall(r'"(bd05\d+\.wav)"', cr_text)) == {"bd05003.wav", "bd05007.wav"}, "the CR layer plays only the two unused lines"
# The debrief bd05win.des ships with the game, not in this tree.
assert 'bd05win.des' in live

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd05cr.bzn"
doc = (ROOT / "Docs/BDMISN05_COOP.md").read_text(encoding="utf-8")
if not bzn_path.is_file():
    print("bdmisn05 co-op contract: map checks SKIPPED, Missions/bd05cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn05\n" in text and "msn_filename = bd05cr.bzn" in text

objects, starts = {}, []
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    assert perceived == team, "perceived team follows the move: " + str(label and label[1])
    if label:
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# Every handle the body asks for is a map object, on the right side.
handles = set(re.findall(r'GetHandle\("(\w+)"\)', live)) | {"unit_%d" % n for n in range(1, 16)}
assert re.search(r'GetHandle\("unit_" \.\. \(i \+ 1\)\)', live), "the body reads unit_1..unit_15 in a loop"
assert handles <= set(objects), "every GetHandle label is a map object: " + str(handles - set(objects))
assert objects["recycler"] == ("bvrecyc", 1) and objects["portal"] == ("cbport", 5), objects["portal"]
for n in range(1, 16):
    assert objects["unit_%d" % n][1] == 5, "the map's ambient units are the co-op enemy"
assert objects["recycler"][0] == "bvrecyc" and "recycler" in config  # the rally point
rally = re.search(r'rallyPoints = \{ \[0\] = "(\w+)" \}', config)[1]
assert rally in objects, "rally point is a map object"
# Every path the body or the CR layer names exists.
used = set(re.findall(r'SpawnUnit\(\d+, "\w+", "(\w+)"', live))
used |= set(re.findall(r'BuildObject\("\w+", 2, "(\w+)"\)', live))
used |= set(re.findall(r'Retreat\([^,]+, "(\w+)"', live))
used |= set(re.findall(r'CameraPath\("(\w+)"', live))
assert used == {"camera_start_arc", "first_wave", "second_wave", "third_wave", "fourth_wave", "rear_attack", "howit",
                "quitters", "portal_in", "camera_retreat"}, used
assert used <= set(paths), "every path the body names exists: " + str(used - set(paths))
fallback = re.search(r"fallbackEntries = \{([^}]*)\}", config)[1]
fallback_paths = re.findall(r'"(\w+)"', fallback)
assert fallback_paths, "there are alternative staging points"
for name in fallback_paths:
    assert name in paths, "fallback spawn entry exists: " + name
assert set(fallback_paths) <= used, "fallbacks are the body's own approaches"
assert "quitters" not in fallback_paths and "howit" not in fallback_paths and "rear_attack" not in fallback_paths
# The three vents the weather uses are geysers the map carries (the sites file is generated from them).
for label in vents:
    assert label in objects and objects[label][0] == "eggeizr1", "vent is a map geyser: " + label

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd05cr.vxt"
ini = ROOT / "Config/bd05cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every named map path
unused = sorted(set(paths) - used)
for name in unused:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
assert unused == ["portal"], unused
assert (ROOT / "Docs/CCA_COOP_RUNTIME.md").is_file()
print("bdmisn05 co-op contract passed: %d objects, %d paths, %d scripted path/label names, Ganymede sites present; %d path unused (documented)"
      % (len(objects), len(paths), len(used) + len(handles), len(unused)))

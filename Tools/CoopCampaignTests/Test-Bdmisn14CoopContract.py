#!/usr/bin/env python3
"""bdmisn14 co-op map contract: the labels, paths and teams Scripts/bd14cr.lua names exist in Missions/bd14cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/MissionBuild/Build-CoopMap.py); the script, the sites, the audio and the doc are always checked.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
lua_full = (ROOT / "Scripts/bd14cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local NativeSetCloaked", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = ENEMY_TEAM" in config and "ENEMY_TEAM = 5" in cr_text
assert "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRGanymedeSitesBD14"' in config and 'module = "CREuropaWeather"' in config
assert 'failDes = "bd14lose.des"' in config, "the out-of-lives failure uses the stock generic debrief"
assert 'wonFlags = { "objective3Complete" }' in config and 'endedFlags = { "wonLost" }' in config
assert 'rallyPoints = { [0] = "recycler" }' in config
assert "safeRadius = 120" in config, "the concealment ring is inside the 150 m ambush trigger"
assert 'ops = { "EuropaState", "EuropaPlume", "EuropaQuake", "EuropaSurge" }' in config
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
spawned = set(re.findall(r'BuildObject\("(\w+)", 2, ', live))
restored_spawned = set(re.findall(r'BuildObject\("(\w+)", 2, ', cr_text))
assert restored_spawned == {"cvturr"}, restored_spawned
assert scaled == (spawned - {"cvapcc", "cvscav"}) | restored_spawned, (sorted(scaled), sorted(spawned))
assert {"cvapcc", "cvscav"} <= spawned and not ({"cvapcc", "cvscav"} & scaled), "the APC and the scavengers are built straight"
fallbacks = re.search(r"fallbackEntries = \{([^}]*)\}", config)[1]
fallbacks = re.findall(r'"(\w+)"', fallbacks)
for module in ("CREuropaWeather", "CRCCARuntime", "CRGanymedeSitesBD14"):
    assert (ROOT / ("Scripts/%s.lua" % module)).is_file(), module
sites = (ROOT / "Scripts/CRGanymedeSitesBD14.lua").read_text(encoding="utf-8")
assert 'mission = "bdmisn14"' in sites, "generated Ganymede sites belong to bdmisn14"
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio and objectives: none is invented
wavs = sorted(set(re.findall(r'"(bd14\d+\.wav)"', lua_full)))
assert wavs == ["bd14%03d.wav" % n for n in range(1, 9)], wavs
for wav in wavs:
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
durations = (ROOT / "Config/durations.csv").read_text(encoding="utf-8")
for wav in wavs:
    assert wav + "," in durations, "no duration for " + wav
# The game ships no unused bd14 voice line: the CR layer plays no line the body does not (the gate that drops the
# late bd14004 lives in the shared body).
assert not set(re.findall(r'"(bd14\d+\.wav)"', cr_text))
assert set(re.findall(r'"(bd14\d+\.wav)"', live)) == set(wavs), "the body plays all eight shipped lines"
otfs = sorted(set(re.findall(r'"(bd14\d+\.otf)"', lua_full)))
assert otfs == ["bd14001.otf", "bd14002.otf", "bd14003.otf"], otfs
for des in ("bd14win.des", "bd14lsea.des", "bd14lseb.des"):
    assert des in live  # the debriefs ship with the game, not in this tree
assert "bd14lose.des" in config

# ---------------------------------------------------------------- the doc
doc = (ROOT / "Docs/BDMISN14_COOP.md").read_text(encoding="utf-8")
for heading in ("## Stock bugs fixed in the CR layer", "## Restored content", "## Weather: Ganymede", "## Live checklist"):
    assert heading in doc, heading
assert "RESTORED_TURRET_CONVOY" in doc and "#if 0" in doc, "the restored block is quoted in the doc"
assert "bd14004" in doc and "bd14lose.des" in doc

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd14cr.bzn"
if not bzn_path.is_file():
    print("bdmisn14 co-op contract: map checks SKIPPED, Missions/bd14cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn14\n" in text and "msn_filename = bd14cr.bzn" in text

objects, starts = {}, []
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    assert perceived == team, "perceived team follows the move: " + str(label and label[1])
    if label:
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# Every handle the body asks for is a map object: the two recyclers and the six cloaked starters.
assert objects["recycler"] == ("bvrecyc", 1), "the shared Black Dog base is team 1"
assert objects["chin_recycler"] == ("cvrecye", 5), "the Chinese recycler is the co-op enemy's"
for side, count in ((1, 3), (2, 3)):
    for n in range(1, count + 1):
        label = "start%d_%d" % (side, n)
        assert label in re.findall(r'GetHandle\("(start\d_\d)"\)', live), label
        assert objects[label][1] == 5, "the cloaked starters are the co-op enemy's: " + label
# Every path the body or the CR layer names exists.
used = {lit for lit in re.findall(r'"(\w+)"', live + cr_text) if lit in set(paths)}
used |= set(fallbacks)
expected = {"spawn_initial_attack", "path_initial_attack", "spawn_attack_waves", "path_attack_waves",
            "spawn_apc", "path_apc_travel", "spawn_turrets", "path_turrets", "spawn_attack_1", "path_attack_1",
            "spawn_attack_2", "path_attack_2", "trigger_attack_1", "trigger_attack_2", "spawn_defend",
            "path_defend", "spawn_scav"}
assert used == expected, (sorted(used ^ expected))
assert used <= set(paths), "every path the body names exists: " + str(used - set(paths))
# The restored convoy needs its two paths; the fallback entries are real approaches.
assert {"spawn_turrets", "path_turrets"} <= set(paths)
assert all(f in paths for f in fallbacks)
# The weather opens the geysers under the Chinese factory and recycler: map geysers at their positions.
vents = re.findall(r'label = "(\w+)"', sites.split("vents = {", 1)[1])
assert len(vents) == 5
for label in vents:
    assert label in objects, "vent is a map geyser: " + label
for label in ("eggeizr13_geyser", "eggeizr15_geyser"):
    assert label in vents and label in cr_text, label

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd14cr.vxt"
ini = ROOT / "Config/bd14cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every named map path
unused = sorted(set(paths) - used)
for name in unused:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
print("bdmisn14 co-op contract passed: %d objects, %d paths, %d scripted path names, Ganymede sites present; %d paths unused (documented)"
      % (len(objects), len(paths), len(used), len(unused)))

#!/usr/bin/env python3
"""bdmisn11 co-op map contract: the labels, paths and teams Scripts/bd11cr.lua names exist in Missions/bd11cr.bzn.

The map, its .vxt and the Config ini are checked only when they are in the tree (the map is generated by
Tools/MissionBuild/Build-CoopMap.py); the script, the sites and the doc are always checked.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
lua_full = (ROOT / "Scripts/bd11cr.lua").read_text(encoding="utf-8")
region = r"(?ms)^-- CR [^\n]* >>\n.*?^-- CR [^\n]* <<\n?"
live = re.sub(region, "", lua_full)
live = re.sub(r"--\[==\[.*?\]==\]", "", live, flags=re.S)  # the DLL's disabled code stays disabled
live = re.sub(r"--[^\n]*", "", live)
cr_text = "".join(re.findall(region, lua_full))
config = lua_full.split('require("CRCCARuntime").Create', 1)[1].split("local NativeBuildObject", 1)[0]

# ---------------------------------------------------------------- the script's own configuration
assert "enemyTeam = 5" in config and "mapEnemyTeam = 2" in config and "leaderTeam = 1" in config
assert 'sites = "CRElysiumSitesBD11"' in config and 'module = "CRElysiumWeather"' in config
assert '"explodePortal"' in config.split("wonFlags", 1)[1].split("\n", 1)[0], "the portal blast latches the result"
assert (ROOT / "Scripts/CRElysiumWeather.lua").is_file() and (ROOT / "Scripts/CRCCARuntime.lua").is_file()
scaled = set(re.search(r"SCALED_ODFS = \{([^}]*)\}", cr_text)[1].replace("=", " ").replace("true", " ").replace(",", " ").split())
body_odfs = set(re.findall(r'"(cv\w+|cssold)"', live))
assert scaled == body_odfs == {"cvfigh", "cvltnk", "cvtnk", "cvhtnk", "cvhraz", "cvwalk", "cssold"}, (scaled, body_odfs)
sites = ROOT / "Scripts/CRElysiumSitesBD11.lua"
sites_text = sites.read_text(encoding="utf-8")
assert 'mission = "bdmisn11"' in sites_text, "generated Elysium sites belong to bdmisn11"
# No Lua string literal may hold an engine basename longer than 8 characters (validator rule).
for literal in re.findall(r'"([^"\n]*)"', live + cr_text):
    m = re.fullmatch(r"([A-Za-z0-9_]+)\.(wav|otf|des|bzn|vxt|ini|odf|lua)", literal)
    assert m is None or len(m[1]) <= 8, "engine basename over 8 characters: " + literal

# ---------------------------------------------------------------- audio and objectives: every line has a subtitle
wavs = sorted(set(re.findall(r'"(bd11\d+\.wav)"', lua_full)))
assert wavs == ["bd11%03d.wav" % n for n in range(1, 13)], wavs
for wav in wavs:
    assert (ROOT / "Text" / (wav[:-4] + ".txt")).is_file(), "no subtitle for " + wav
body_wavs = set(re.findall(r'"(bd11\d+\.wav)"', live))
assert body_wavs == set(wavs) - {"bd11003.wav"}, body_wavs
assert set(re.findall(r'"(bd11\d+\.wav)"', cr_text)) == {"bd11003.wav"}, "the CR layer plays only the one unused line"
assert set(re.findall(r'"(bd11\d+\.otf)"', live)) == {"bd11001.otf", "bd11002.otf", "bd11003.otf"}
assert set(re.findall(r'"(bd11\d+\.otf)"', cr_text)) == {"bd11004.otf"}, "the CR layer shows only the one unused objective"
# The debriefs ship with the game, not in this tree.
assert set(re.findall(r'"(bd11\w+\.des)"', lua_full)) == {"bd11lsea.des", "bd11lseb.des", "bd11lsec.des",
                                                       "bd11lsed.des", "bd11lsee.des", "bd11win.des"}

# ---------------------------------------------------------------- the map
bzn_path = ROOT / "Missions/bd11cr.bzn"
doc = (ROOT / "Docs/BDMISN11_COOP.md").read_text(encoding="utf-8")
if not bzn_path.is_file():
    print("bdmisn11 co-op contract: map checks SKIPPED, Missions/bd11cr.bzn is not present")
    sys.exit(0)

text = bzn_path.read_bytes().decode("latin-1").replace("\r\n", "\n")
assert "TerrainName = bdmisn11\n" in text and "msn_filename = bd11cr.bzn" in text

objects, starts = {}, []
for block in text.split("[GameObject]\n")[1:]:
    label = re.search(r"^label = (.*)$", block, re.M)
    odf = re.search(r"^PrjID \[1\] =\n(.*)$", block, re.M)[1]
    team = int(re.search(r"^team \[1\] =\n(\d+)$", block, re.M)[1])
    perceived = int(re.search(r"^perceivedTeam \[1\] =\n(\d+)$", block, re.M)[1])
    if odf == "pspwn_1":
        starts.append(team)
        continue
    assert team in (0, 1, 5), "authored teams are neutral, Black Dog or the co-op enemy 5: %s team %d" % (odf, team)
    if label and label[1] != "recycler":
        assert perceived == team, "perceived team follows the move: " + label[1]
    if label:
        objects.setdefault(label[1], (odf, team))
assert sorted(starts) == [1, 2, 3, 4], "one start buoy per human team"
paths = []
for path in text.split("[AiPath]\n")[1:]:
    m = re.search(r"^label = (.*)$", path.split("pointCount", 1)[0], re.M)
    if m:
        paths.append(m[1])

# Every handle the body asks for is a map object, on the right side.
handles = set(re.findall(r'GetHandle\("(\w+)"\)', live)) | {"enemy_%d" % n for n in range(1, 7)}
assert re.search(r'GetHandle\("enemy_" \.\. \(i \+ 1\)\)', live), "the body reads enemy_1..enemy_6 in a loop"
assert handles <= set(objects), "every GetHandle label is a map object: " + str(handles - set(objects))
# The Recycler is an unmanned Black Dog craft (team 1, perceived neutral until the pilot boards); the portal is Chinese.
assert objects["recycler"] == ("bvrecya", 1) and objects["portal"] == ("cbport", 5) and objects["apc"] == ("bvapc", 1), objects
for n in range(1, 7):
    assert objects["enemy_%d" % n][1] == 5, "the map's ambient raiders are the co-op enemy"
rally = re.search(r'rallyPoints = \{ \[0\] = "(\w+)" \}', config)[1]
assert rally in objects, "rally point is a map object"
# Every path the body or the CR layer names exists (the wave tables name attack_N / defend_N literally).
used = {name for name in re.findall(r'"(\w+)"', live) if name in paths}
used |= {name for name in re.findall(r'"(\w+)"', cr_text) if name in paths and name != "recycler_deploy"}
expected = ({"camera_start", "camera_destruct", "recy_nav", "recycler_path", "wave_trigger", "drive_1", "drive_2",
             "aerial_1", "dw_1", "dw_2", "dw_3", "dw_4", "nav_end"}
            | {"attack_%d" % n for n in range(1, 7)} | {"defend_%d" % n for n in range(1, 7)})
assert used == expected, (sorted(used - expected), sorted(expected - used))
fallback = re.search(r"fallbackEntries = \{([^}]*)\}", config)[1]
fallback_paths = re.findall(r'"(\w+)"', fallback)
assert fallback_paths, "there are alternative staging points"
for name in fallback_paths:
    assert name in paths, "fallback spawn entry exists: " + name
assert set(fallback_paths) <= used, "fallbacks are the body's own approaches"
assert not set(fallback_paths) & {"aerial_1", "drive_2", "nav_end", "recy_nav", "wave_trigger", "dw_1", "dw_2", "dw_3", "dw_4"}, \
    "fallbacks are far from the base"
# The vents the Elysium sites list are map geysers.
for label in re.findall(r'label = "(\w+)"', sites_text.split("vents = {", 1)[1]):
    assert label in objects and objects[label][0] == "eggeizr1", "vent is a map geyser: " + label

# The surrounding companions of a mission entry (checked when present).
vxt = ROOT / "Missions/bd11cr.vxt"
ini = ROOT / "Config/bd11cr.ini"
if vxt.is_file():
    assert vxt.stat().st_size > 0
if ini.is_file():
    assert "[MULTIPLAYER]" in ini.read_text(encoding="utf-8")

# ---------------------------------------------------------------- the doc accounts for every named map path
unused = sorted(set(paths) - used)
for name in unused:
    assert "`" + name + "`" in doc, "undocumented unused map path: " + name
assert unused == ["aerial_2", "apc_goes_here", "arrival_1", "backup_1", "defend_area_1", "edge_path", "incoming_1",
                  "path_4", "retreat_1", "retreat_2", "trigger_1"], unused
assert (ROOT / "Docs/CCA_COOP_RUNTIME.md").is_file()
print("bdmisn11 co-op contract passed: %d objects, %d paths, %d scripted path/label names, Elysium sites present; %d paths unused (documented)"
      % (len(objects), len(paths), len(used) + len(handles), len(unused)))
